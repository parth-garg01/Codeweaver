from __future__ import annotations

import unittest

from codeweaver.backends.typescript.module import (
    ModuleLayout,
    generate_module,
    output_path_for,
)
from codeweaver.frontends.python import parse_source


def ir_module(source: str, path: str = "pkg/mod.py"):
    result = parse_source(source, path)
    assert result.module is not None, [d.format() for d in result.diagnostics]
    return result.module


def generate(source: str, path: str = "pkg/mod.py"):
    module = ir_module(source, path)
    return generate_module(module)


class OutputPathTests(unittest.TestCase):
    def test_module_path(self) -> None:
        self.assertEqual(output_path_for("pkg/mod.py"), "pkg/mod.ts")

    def test_package_init_becomes_index(self) -> None:
        self.assertEqual(output_path_for("pkg/__init__.py"), "pkg/index.ts")

    def test_top_level_module(self) -> None:
        self.assertEqual(output_path_for("main.py"), "main.ts")


class ModuleLayoutTests(unittest.TestCase):
    def layout(self) -> ModuleLayout:
        return ModuleLayout(
            {
                "pkg": "pkg/index.ts",
                "pkg.models": "pkg/models.ts",
                "pkg.service": "pkg/service.ts",
                "pkg.deep.inner": "pkg/deep/inner.ts",
                "main": "main.ts",
            }
        )

    def test_sibling_module(self) -> None:
        self.assertEqual(self.layout().specifier("pkg.service", "pkg.models"), "./models")

    def test_nested_module(self) -> None:
        self.assertEqual(self.layout().specifier("pkg.service", "pkg.deep.inner"), "./deep/inner")

    def test_parent_module(self) -> None:
        self.assertEqual(self.layout().specifier("pkg.deep.inner", "pkg.models"), "../models")

    def test_from_root_into_a_package(self) -> None:
        self.assertEqual(self.layout().specifier("main", "pkg.models"), "./pkg/models")

    def test_unknown_module_has_no_specifier(self) -> None:
        self.assertIsNone(self.layout().specifier("pkg.service", "requests"))

    def test_built_from_modules(self) -> None:
        layout = ModuleLayout.for_modules([ir_module("x = 1", "a/b.py")])
        self.assertEqual(layout.paths, {"a.b": "a/b.ts"})


