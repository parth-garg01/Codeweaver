class ImportEmitTests(unittest.TestCase):
    def test_project_import_uses_a_relative_specifier(self) -> None:
        modules = [
            ir_module("def helper():\n    pass\n", "pkg/util.py"),
            ir_module("from pkg.util import helper\n", "pkg/app.py"),
        ]
        layout = ModuleLayout.for_modules(modules)
        generated = generate_module(modules[1], layout)
        self.assertIn('import { helper } from "./util";', generated.contents)

    def test_relative_import_resolves(self) -> None:
        modules = [
            ir_module("def helper():\n    pass\n", "pkg/util.py"),
            ir_module("from .util import helper\n", "pkg/app.py"),
        ]
        layout = ModuleLayout.for_modules(modules)
        generated = generate_module(modules[1], layout)
        self.assertIn('from "./util"', generated.contents)

    def test_import_alias_is_preserved(self) -> None:
        modules = [
            ir_module("def helper():\n    pass\n", "pkg/util.py"),
            ir_module("from pkg.util import helper as h\n", "pkg/app.py"),
        ]
        generated = generate_module(modules[1], ModuleLayout.for_modules(modules))
        self.assertIn("{ helper as h }", generated.contents)

    def test_whole_module_import_becomes_a_namespace_import(self) -> None:
        modules = [
            ir_module("x = 1\n", "pkg/util.py"),
            ir_module("import pkg.util\n", "pkg/app.py"),
        ]
        generated = generate_module(modules[1], ModuleLayout.for_modules(modules))
        # The binding is the flattened dotted path, so two modules whose
        # last component matches cannot collide (see issue #2).
        self.assertIn('import * as pkg_util from "./util";', generated.contents)

    def test_external_import_is_reported(self) -> None:
        generated = generate("import os\n")
        self.assertIn("CW0640", [item.code for item in generated.diagnostics])
        self.assertIn('import * as os from "os";', generated.contents)


class FunctionEmitTests(unittest.TestCase):
    def test_function_is_exported_with_types(self) -> None:
        generated = generate("def add(a: int, b: int) -> int:\n    return a + b\n")
        self.assertIn("export function add(a: number, b: number): number {", generated.contents)
        self.assertIn("return a + b;", generated.contents)

    def test_private_function_is_not_exported(self) -> None:
        generated = generate("def _helper():\n    pass\n")
        self.assertIn("function _helper()", generated.contents)
        self.assertNotIn("export function _helper", generated.contents)

    def test_async_function_returns_a_promise(self) -> None:
        generated = generate("async def fetch() -> int:\n    return 1\n")
        self.assertIn("export async function fetch(): Promise<number> {", generated.contents)

    def test_docstring_becomes_a_jsdoc_comment(self) -> None:
        generated = generate('def f():\n    """Do it."""\n    pass\n')
        self.assertIn(" * Do it.", generated.contents)

    def test_unapplied_decorator_is_noted(self) -> None:
        generated = generate("@lru_cache\ndef f():\n    pass\n")
        self.assertIn("// decorator not applied: lru_cache", generated.contents)


class ModuleVariableEmitTests(unittest.TestCase):
    def test_uppercase_variable_is_an_exported_const(self) -> None:
        generated = generate("VERSION = '1'\n")
        self.assertIn('export const VERSION = "1";', generated.contents)

    def test_lowercase_variable_is_an_exported_let(self) -> None:
        generated = generate("counter = 0\n")
        self.assertIn("export let counter = 0;", generated.contents)

    def test_underscore_variable_is_not_exported(self) -> None:
        generated = generate("_cache = {}\n")
        self.assertIn("let _cache = {};", generated.contents)
        self.assertNotIn("export let _cache", generated.contents)


class ClassEmitTests(unittest.TestCase):
    SOURCE = (
        "class Account(Base):\n"
        '    """An account."""\n'
        "    kind = 'savings'\n"
        "    balance: int = 0\n"
        "    _audit: bool = False\n"
        "\n"
        "    def __init__(self, owner: str) -> None:\n"
        "        super().__init__()\n"
        "        self.owner = owner\n"
        "\n"
        "    def deposit(self, amount: int) -> None:\n"
        "        self.balance += amount\n"
        "\n"
        "    @staticmethod\n"
        "    def make() -> 'Account':\n"
        "        return Account('x')\n"
    )

    def setUp(self) -> None:
        self.contents = generate(self.SOURCE).contents

    def test_class_extends_its_base_and_is_exported(self) -> None:
        self.assertIn("export class Account extends Base {", self.contents)

    def test_class_docstring(self) -> None:
        self.assertIn(" * An account.", self.contents)

    def test_static_and_instance_fields(self) -> None:
        self.assertIn('static kind: unknown = "savings";', self.contents)
        self.assertIn("balance: number = 0;", self.contents)

    def test_protected_field_gains_a_modifier(self) -> None:
        self.assertIn("protected _audit: boolean = false;", self.contents)

    def test_constructor_has_no_receiver_parameter(self) -> None:
        self.assertIn("constructor(owner: string) {", self.contents)

    def test_super_init_becomes_a_super_call(self) -> None:
        self.assertIn("super();", self.contents)

    def test_receiver_references_become_this(self) -> None:
        self.assertIn("this.owner = owner;", self.contents)
        self.assertIn("this.balance += amount;", self.contents)
        self.assertNotIn("self.", self.contents)

    def test_static_method_is_marked_static(self) -> None:
        self.assertIn("static make(): Account {", self.contents)

    def test_multiple_inheritance_is_reported(self) -> None:
        generated = generate("class C(A, B):\n    pass\n")
        self.assertIn("CW0641", [item.code for item in generated.diagnostics])
        self.assertIn("class C extends A {", generated.contents)

    def test_abstract_method_has_no_body(self) -> None:
        generated = generate(
            "class C:\n    @abstractmethod\n    def f(self) -> int:\n        ...\n"
        )
        self.assertIn("abstract f(): number;", generated.contents)

    def test_handled_decorators_are_not_repeated_as_comments(self) -> None:
        generated = generate("class C:\n    @staticmethod\n    def f() -> int:\n        return 1\n")
        self.assertNotIn("decorator not applied", generated.contents)

    def test_property_becomes_a_getter(self) -> None:
        generated = generate(
            "class C:\n    @property\n    def total(self) -> int:\n        return 1\n"
        )
        self.assertIn("get total(): number {", generated.contents)


class GapTrackingTests(unittest.TestCase):
    def test_unsupported_constructs_are_counted_and_marked(self) -> None:
        generated = generate("def f(xs):\n    return (x for x in xs)\n")
        self.assertEqual(generated.unsupported_count, 1)
        self.assertIn("CODEWEAVER-UNSUPPORTED", generated.contents)

    def test_clean_module_reports_no_gaps(self) -> None:
        generated = generate("def f(a: int) -> int:\n    return a\n")
        self.assertEqual(generated.unsupported_count, 0)

    def test_mapping_metadata_is_produced(self) -> None:
        generated = generate("def f(a: int) -> int:\n    return a\n")
        self.assertTrue(generated.mappings)
        self.assertEqual(generated.mappings[0]["sourceFile"], "pkg/mod.py")

    def test_to_dict_summarises_the_file(self) -> None:
        payload = generate("x = 1\n").to_dict()
        self.assertEqual(payload["path"], "pkg/mod.ts")
        self.assertGreater(payload["lineCount"], 0)


class DeterminismTests(unittest.TestCase):
    def test_generation_is_byte_identical_across_runs(self) -> None:
        source = ClassEmitTests.SOURCE
        self.assertEqual(generate(source).contents, generate(source).contents)

    def test_output_ends_with_a_single_newline(self) -> None:
        contents = generate("x = 1\n").contents
        self.assertTrue(contents.endswith("\n"))
        self.assertFalse(contents.endswith("\n\n"))


