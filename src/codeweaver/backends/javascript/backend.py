"""The JavaScript target backend.

JavaScript is emitted by the same generator as TypeScript, with the dialect
flag turned off.  That is not a shortcut: as far as code generation is
concerned the two languages differ only in type syntax, so every other decision
— operator precedence, statement shapes, builtin mapping, exception mapping,
import specifiers — is identical.  Two copies of that logic would drift, and a
bug fixed in one would survive in the other.

The two backends are not interchangeable to a *user*, though, and this module
is where the difference lives:

* the output is ES modules in ``.js`` files, with a ``package.json`` that says
  ``"type": "module"`` — without it Node reads the files as CommonJS and the
  ``export`` keyword is a syntax error;
* validation is a syntax check (``node --check``) rather than a type check,
  which catches far less.  The limitation list says so, and the migration
  report records which check actually ran.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

from codeweaver.backends.typescript.module import (
    JAVASCRIPT,
    GeneratedFile,
    ModuleLayout,
    generate_module,
    output_path_for,
)
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.ir.declarations import IRModule

__all__ = ["JavaScriptBackend", "project_files", "render_package_json"]


def render_package_json(name: str, version: str = "0.0.0") -> str:
    """Render ``package.json`` for the generated project.

    ``"type": "module"`` is load-bearing: the generated files use ``import`` and
    ``export``, and without it Node parses them as CommonJS and refuses.
    """
    payload = {
        "name": name or "codeweaver-output",
        "version": version or "0.0.0",
        "private": True,
        "type": "module",
        "description": "Generated by CodeWeaver. Review before use.",
        "scripts": {"check": "node --check *.js"},
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def project_files(project_name: str) -> dict[str, str]:
    """The non-source files a generated JavaScript project needs."""
    return {"package.json": render_package_json(project_name)}


@dataclass
class JavaScriptBackend:
    """Backend adapter for JavaScript (ES modules)."""

    language: str = "javascript"
    display_name: str = "JavaScript (ES2022, modules)"
    file_extension: str = ".js"
    supported_constructs: tuple[str, ...] = field(
        default_factory=lambda: (
            "modules with relative ESM imports",
            "exported constants, functions and classes",
            "classes with single inheritance, fields, methods and accessors",
            "constructors, including super() delegation",
            "async functions",
            "parameters with defaults and rest parameters",
            "arithmetic, bitwise, logical and strict comparison operators",
            "floor division lowered to Math.floor",
            "template literals from f-strings",
            "array, Set and object literals",
            "comprehensions as array method chains",
            "if/else-if chains, while, for-of and counted for loops",
            "try/catch with instanceof dispatch, finally, throw",
        )
    )
    known_limitations: tuple[str, ...] = field(
        default_factory=lambda: (
            "validation is a syntax check only: node --check cannot catch a "
            "type error, so a passing check says much less than it does for "
            "TypeScript",
            "type annotations are erased, so nothing records what the source "
            "declared; migrate to TypeScript if that matters",
            "private and protected members become public: JavaScript's #name "
            "fields rename the member and are invisible to subclasses, which "
            "is not the same thing",
            "abstract members lose their abstract marker and are reported",
            "keyword arguments become a trailing options object, which the callee must accept",
            "while/else and for/else bodies are reported, not emitted",
            "try/else bodies move inside the try block and become catchable",
            "integer arithmetic becomes IEEE-754 double arithmetic",
        )
    )
    required_toolchains: tuple[str, ...] = field(default_factory=lambda: ("node",))

    def generate_module(
        self,
        module: IRModule,
        layout: ModuleLayout | None = None,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> GeneratedFile:
        return generate_module(module, layout, diagnostics=diagnostics, dialect=JAVASCRIPT)

    def generate_project(
        self,
        modules: list[IRModule],
        *,
        project_name: str = "codeweaver-output",
        diagnostics: DiagnosticBag | None = None,
    ) -> dict[str, str]:
        layout = ModuleLayout.for_modules(modules, dialect=JAVASCRIPT)
        files = project_files(project_name)
        for module in sorted(modules, key=lambda item: item.name):
            generated = self.generate_module(module, layout, diagnostics=diagnostics)
            files[generated.path] = generated.contents
        return files

    def output_path(self, source_path: str) -> str:
        return output_path_for(source_path, extension=self.file_extension)

    def layout_for(self, modules: list[IRModule]) -> ModuleLayout:
        return ModuleLayout.for_modules(modules, dialect=JAVASCRIPT)

    def project_files(self, project_name: str) -> dict[str, str]:
        return project_files(project_name)
