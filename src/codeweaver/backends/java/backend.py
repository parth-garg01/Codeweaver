"""The Java 17 target backend and the project files it scaffolds.

The generated project uses the standard Maven layout (``src/main/java``) and
builds with ``mvn package`` or plain ``javac``.  Its only dependency is the
single-file runtime ``cwrt/Py.java`` that ships with it.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from typing import Any
from xml.sax.saxutils import escape

from codeweaver.backends.common.files import GeneratedFile
from codeweaver.backends.java.context import RUNTIME_PATH, SOURCE_ROOT, JavaLayout
from codeweaver.backends.java.module import generate_module_files
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.project_index import ProjectIndex
from codeweaver.ir.declarations import IRModule

__all__ = ["JavaBackend", "render_pom", "runtime_source"]


def runtime_source() -> str:
    return (
        resources.files("codeweaver.backends.java")
        .joinpath("runtime/Py.java")
        .read_text(encoding="utf-8")
    )


def _artifact(project_name: str) -> str:
    cleaned = "".join(char.lower() if char.isalnum() else "-" for char in project_name).strip("-")
    return cleaned or "codeweaver-output"


def render_pom(project_name: str, layout: JavaLayout) -> str:
    main_class = ""
    if len(layout.entry_modules) == 1:
        module = layout.entry_modules[0]
        main_class = layout.qualified_class(module, layout.module_classes[module])
    manifest = (
        "        <plugin>\n"
        "          <groupId>org.apache.maven.plugins</groupId>\n"
        "          <artifactId>maven-jar-plugin</artifactId>\n"
        "          <version>3.4.2</version>\n"
        "          <configuration>\n"
        "            <archive><manifest><mainClass>"
        f"{escape(main_class)}"
        "</mainClass></manifest></archive>\n"
        "          </configuration>\n"
        "        </plugin>\n"
        if main_class
        else ""
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by CodeWeaver. Review before use. -->\n"
        '<project xmlns="http://maven.apache.org/POM/4.0.0"\n'
        '         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n'
        '         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">\n'
        "  <modelVersion>4.0.0</modelVersion>\n"
        "  <groupId>codeweaver.generated</groupId>\n"
        f"  <artifactId>{escape(_artifact(project_name))}</artifactId>\n"
        "  <version>0.1.0</version>\n"
        "  <properties>\n"
        "    <maven.compiler.release>17</maven.compiler.release>\n"
        "    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>\n"
        "  </properties>\n"
        "  <build>\n"
        "    <plugins>\n"
        f"{manifest}"
        "    </plugins>\n"
        "  </build>\n"
        "</project>\n"
    )


@dataclass
class JavaBackend:
    """Backend adapter registered in the language registry."""

    language: str = "java"
    display_name: str = "Java 17"
    file_extension: str = ".java"
    supported_constructs: tuple[str, ...] = field(
        default_factory=lambda: (
            "modules as packages, with a final class for module-level functions and variables",
            "classes with single inheritance, fields, methods, properties and static members",
            "constructors, including super().__init__ and inherited constructors",
            "exceptions mapped onto Java's own (ValueError -> IllegalArgumentException, ...)",
            "try/except/else/finally with exact else ordering",
            "for/else and while/else with exact semantics",
            "keyword arguments matched to the callee's signature, defaults filled in",
            "Python semantics for /, //, %, ** and negative indexing",
            "list, set and insertion-ordered dict literals and comprehensions",
            "f-strings, str() and print() with Python's formatting",
            "builtins: len, print, str, int, float, bool, abs, round, min, max, sum, sorted, list, set, range, isinstance, any, all",
            "str, list, dict and set methods",
            "math module functions and constants",
            "if __name__ == '__main__' blocks as main methods",
        )
    )
    known_limitations: tuple[str, ...] = field(
        default_factory=lambda: (
            "int is a 64-bit long; Python's arbitrary precision is not modelled",
            "parameters without annotations are declared as Object",
            "async/await, generators, with, match and nested functions are reported, not translated",
            "multiple inheritance keeps only the first base class",
            "'and'/'or' used for its value requires side-effect-free operands",
        )
    )
    required_toolchains: tuple[str, ...] = field(default_factory=lambda: ("javac",))
    uses_type_inference: bool = True

    def create_layout(self, modules: list[IRModule], index: Any = None) -> JavaLayout:
        project = index if isinstance(index, ProjectIndex) else ProjectIndex.build(modules)
        return JavaLayout.build(modules, project)

    def generate_files(
        self, module: IRModule, layout: JavaLayout, *, diagnostics: DiagnosticBag | None = None
    ) -> list[GeneratedFile]:
        return generate_module_files(module, layout, diagnostics=diagnostics)

    def generate_module(
        self,
        module: IRModule,
        layout: JavaLayout | None = None,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> GeneratedFile:
        """The module class (the registry protocol's single-file view)."""
        layout = layout or self.create_layout([module])
        return self.generate_files(module, layout, diagnostics=diagnostics)[0]

    def project_files(self, project_name: str, layout: JavaLayout) -> dict[str, str]:
        return {
            "pom.xml": render_pom(project_name, layout),
            f"{SOURCE_ROOT}/{RUNTIME_PATH}": runtime_source(),
        }
