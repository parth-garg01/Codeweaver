"""IR modules to Java source files.

One Python module produces one file per class plus a final class for its
module-level functions and variables.  Module-level statements other than
declarations run in a ``static`` initialiser, which is the closest Java has to
Python running a module body on import: both run once, before first use.
"""

from __future__ import annotations

from collections import Counter

from codeweaver.backends.common.analysis import escaping_loop_variables, is_main_guard, local_names
from codeweaver.backends.common.files import GeneratedFile
from codeweaver.backends.common.writer import CodeWriter
from codeweaver.backends.java.context import JavaContext, JavaLayout
from codeweaver.backends.java.expressions import emit_expression, lower_arguments
from codeweaver.backends.java.naming import safe_identifier
from codeweaver.backends.java.statements import can_complete, emit_block, emit_statement
from codeweaver.backends.java.types import EXCEPTIONS, default_value, render_type
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.project_index import ClassInfo
from codeweaver.ir.base import walk
from codeweaver.ir.declarations import IRClass, IRField, IRFunction, IRModule
from codeweaver.ir.expressions import IRAttribute, IRCall, IRName, IRParam
from codeweaver.ir.statements import (
    IRAssign,
    IRAugAssign,
    IRBlock,
    IRComment,
    IRExpressionStatement,
    IRForRange,
    IRNoOp,
    IRVarDecl,
)
from codeweaver.ir.types import TypeKind

__all__ = ["generate_module_files"]

_BANNER = (
    "// Generated by CodeWeaver from {source}.",
    "// Review before use: a successful compile does not prove equivalent behaviour.",
)
_STANDARD_IMPORTS = ("java.util.*", "cwrt.Py")


def _javadoc(writer: CodeWriter, text: str) -> None:
    if not text:
        return
    writer.line("/**")
    for line in text.strip().split("\n"):
        writer.line(f" * {line.replace('*/', '* /')}".rstrip())
    writer.line(" */")


def _reassigned(function: IRFunction) -> set[str]:
    """Locals Java does not treat as effectively final."""
    counts: Counter[str] = Counter(param.name for param in function.params)
    for node in walk(function.body):
        if isinstance(node, IRVarDecl):
            counts[node.name] += 1 if node.value is not None else 2
        elif isinstance(node, IRAssign) and isinstance(node.target, IRName):
            counts[node.target.name] += 1
        elif isinstance(node, IRAugAssign) and isinstance(node.target, IRName):
            counts[node.target.name] += 2
        elif isinstance(node, IRForRange):
            counts[node.variable] += 2
    return {name for name, count in counts.items() if count > 1}


def _enter(function: IRFunction, ctx: JavaContext) -> None:
    ctx.function = function
    ctx.locals = local_names(function)
    receiver = str(function.meta.get("pythonReceiver", ""))
    is_classmethod = bool(function.meta.get("pythonClassMethod"))
    ctx.receiver = "" if is_classmethod else receiver
    ctx.class_receiver = receiver if is_classmethod else ""
    ctx.locals.discard(receiver)
    ctx.escaping = escaping_loop_variables(function.body)
    ctx.declared = set()
    ctx.reassigned = _reassigned(function) | ctx.escaping
    ctx.renames = {}
    ctx.pre = []


def _leave(ctx: JavaContext) -> None:
    ctx.function = None
    ctx.locals = set()
    ctx.receiver = ctx.class_receiver = ""
    ctx.escaping = set()
    ctx.reassigned = set()
    ctx.renames = {}


def _param(param: IRParam, ctx: JavaContext) -> str:
    name = safe_identifier(param.name)
    if param.style == "var_positional":
        element = render_type(param.param_type, ctx, boxed=True)
        return f"List<{element or 'Object'}> {name}"
    if param.style == "var_keyword":
        ctx.warn("CW0692", f"**{param.name} is not translated to Java", span=param.span)
        return f"Map<String, Object> {name}"
    spelled = render_type(param.param_type, ctx)
    if spelled is None:
        ctx.warn(
            "CW0693",
            f"parameter {param.name!r} has no known type; it is declared as Object",
            span=param.span,
            hint="annotate it so the generated code can be type-checked",
        )
        spelled = "Object"
    return f"{spelled} {name}"


def _params(function: IRFunction, ctx: JavaContext) -> str:
    return ", ".join(_param(param, ctx) for param in function.params)


def _return_type(function: IRFunction, ctx: JavaContext) -> str:
    if function.is_async:
        ctx.warn(
            "CW0694",
            f"async function {function.name!r} is generated as a synchronous method",
            span=function.span,
        )
    spelled = render_type(function.return_type, ctx, returning=True)
    if spelled is None:
        if function.return_type.kind is TypeKind.UNKNOWN and not any(
            getattr(node, "value", None) is not None
            for node in walk(function.body)
            if node.kind == "return"
        ):
            return "void"
        ctx.warn(
            "CW0695",
            f"return type of {function.name!r} is unknown; it is declared as Object",
            span=function.span,
            hint="annotate the return type",
        )
        return "Object"
    return spelled


def _body(
    function: IRFunction, writer: CodeWriter, ctx: JavaContext, body: IRBlock | None = None
) -> None:
    _enter(function, ctx)
    block = body if body is not None else function.body
    writer.indent()
    if block.is_empty:
        writer.line("// pass")
    emit_block(block, writer, ctx)
    returns = _return_type(function, ctx) if not function.is_constructor else "void"
    if returns != "void" and can_complete(block):
        # Python would return None here; Java requires every path to return.
        writer.line('throw new Py.TypeError("function ended without returning a value");')
    writer.dedent()
    _leave(ctx)


def _decorators(writer: CodeWriter, function: IRFunction) -> None:
    for decorator in function.decorators:
        text = decorator.source_text.lstrip("@")
        if text not in ("staticmethod", "classmethod", "property", "abstractmethod", "override"):
            writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")


# ---------------------------------------------------------------- assembly


def _assemble(body: CodeWriter, ctx: JavaContext, module: IRModule) -> CodeWriter:
    writer = CodeWriter(indent_text="    ")
    for line in _BANNER:
        writer.line(line.format(source=module.path or module.name))
    if ctx.package:
        writer.line(f"package {ctx.package};")
    writer.blank()
    for item in (*_STANDARD_IMPORTS, *sorted(ctx.imports)):
        writer.line(f"import {item};")
    writer.blank()
    writer.extend(body)
    return writer


def _context(
    module: IRModule,
    layout: JavaLayout,
    simple: str,
    diagnostics: DiagnosticBag,
    *,
    is_module: bool,
) -> JavaContext:
    return JavaContext(
        source_path=module.path,
        output_path=layout.file_for(module.name, simple),
        diagnostics=diagnostics,
        layout=layout,
        index=layout.index,
        module=module,
        file_class=simple,
        is_module_class=is_module,
    )


def generate_module_files(
    module: IRModule, layout: JavaLayout, *, diagnostics: DiagnosticBag | None = None
) -> list[GeneratedFile]:
    bag = diagnostics if diagnostics is not None else DiagnosticBag()
    files: list[GeneratedFile] = []
    simple = layout.module_classes[module.name]
    ctx = _context(module, layout, simple, bag, is_module=True)
    body = _module_class(module, simple, ctx)
    writer = _assemble(body, ctx, module)
    files.append(
        GeneratedFile(
            path=ctx.output_path,
            source_path=module.path,
            contents=writer.render(),
            mappings=writer.mapping_dict(),
            diagnostics=bag,
            unsupported_count=len(ctx.gaps),
            gaps=list(ctx.gaps),
        )
    )
    for klass in module.classes:
        class_name = layout.class_names[f"{module.name}.{klass.name}"]
        class_ctx = _context(module, layout, class_name, bag, is_module=False)
        body = _class_file(klass, class_name, class_ctx)
        writer = _assemble(body, class_ctx, module)
        files.append(
            GeneratedFile(
                path=class_ctx.output_path,
                source_path=module.path,
                contents=writer.render(),
                mappings=writer.mapping_dict(),
                diagnostics=bag,
                unsupported_count=len(class_ctx.gaps),
                gaps=list(class_ctx.gaps),
            )
        )
    return files


# ------------------------------------------------------------ module class


def _is_docstring(statement) -> bool:
    expression = getattr(statement, "expression", None)
    return (
        isinstance(statement, IRExpressionStatement)
        and getattr(expression, "kind", "") == "literal"
        and isinstance(getattr(expression, "value", None), str)
    )


def _module_class(module: IRModule, simple: str, ctx: JavaContext) -> CodeWriter:
    writer = CodeWriter(indent_text="    ")
    _javadoc(writer, module.docstring)
    writer.line(f"public final class {simple} {{", module.span)
    writer.indent()
    writer.line(f"private {simple}() {{}}")
    initialiser: list = []
    for statement in module.body:
        if isinstance(statement, IRVarDecl):
            _module_variable(statement, writer, ctx)
        elif (
            is_main_guard(statement)
            or isinstance(statement, IRComment | IRNoOp)
            or _is_docstring(statement)
        ):
            continue
        else:
            initialiser.append(statement)
    if initialiser:
        writer.blank()
        writer.line("// Module-level statements: run once, when the class is first used.")
        writer.line("static {")
        fake = IRFunction("<module>", body=IRBlock(initialiser))
        _enter(fake, ctx)
        writer.indent()
        for statement in initialiser:
            emit_statement(statement, writer, ctx)
        writer.dedent()
        _leave(ctx)
        writer.line("}")
    for function in module.functions:
        writer.blank()
        _javadoc(writer, function.docstring)
        _decorators(writer, function)
        writer.line(
            f"public static {_return_type(function, ctx)} {safe_identifier(function.name)}({_params(function, ctx)}) {{",
            function.span,
        )
        _body(function, writer, ctx)
        writer.line("}")
    guard = next((statement for statement in module.body if is_main_guard(statement)), None)
    if guard is not None:
        writer.blank()
        writer.line("public static void main(String[] args) {")
        writer.indent()
        writer.line(f"Py.runMain({simple}::cwMain);")
        writer.dedent()
        writer.line("}")
        writer.blank()
        writer.line("private static void cwMain() {", guard.span)
        main = IRFunction("__main__", body=guard.then_body)  # type: ignore[attr-defined]
        _body(main, writer, ctx)
        writer.line("}")
    writer.dedent()
    writer.line("}")
    return writer


def _module_variable(statement: IRVarDecl, writer: CodeWriter, ctx: JavaContext) -> None:
    spelled = render_type(statement.var_type, ctx)
    name = safe_identifier(statement.name)
    if spelled is None:
        ctx.warn(
            "CW0695",
            f"module variable {statement.name!r} has an unknown type; it is declared as Object",
            span=statement.span,
        )
        spelled = "Object"
    final = "final " if statement.is_const else ""
    if statement.value is None:
        writer.line(
            f"public static {final}{spelled} {name} = {default_value(spelled)};", statement.span
        )
        return
    _enter(IRFunction("<module>"), ctx)
    value = emit_expression(statement.value, ctx, statement.var_type).text
    _leave(ctx)
    writer.line(f"public static {final}{spelled} {name} = {value};", statement.span)


# ------------------------------------------------------------- class files


def _base(info: ClassInfo | None, ctx: JavaContext) -> str:
    if info is None:
        return ""
    if info.base and ctx.index is not None and info.base in ctx.index.classes:
        return ctx.class_spelling(ctx.index.classes[info.base])
    if info.builtin_base:
        return EXCEPTIONS.get(info.builtin_base, "RuntimeException")
    return ""


def _super_init(statement) -> IRCall | None:
    if not isinstance(statement, IRExpressionStatement):
        return None
    call = statement.expression
    if (
        isinstance(call, IRCall)
        and isinstance(call.callee, IRAttribute)
        and call.callee.name == "__init__"
    ):
        target = call.callee.target
        if (
            isinstance(target, IRCall)
            and isinstance(target.callee, IRName)
            and target.callee.name == "super"
        ):
            return call
    return None


def _class_file(klass: IRClass, simple: str, ctx: JavaContext) -> CodeWriter:
    writer = CodeWriter(indent_text="    ")
    info = ctx.own_class(klass)
    ctx.klass = info
    _javadoc(writer, klass.docstring)
    if len(klass.bases) > 1:
        ctx.warn(
            "CW0696",
            f"class {klass.name!r} has several base classes; Java keeps only the first",
            span=klass.span,
        )
    for decorator in klass.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    base = _base(info, ctx)
    abstract = "abstract " if info is not None and info.is_abstract else ""
    extends = f" extends {base}" if base else ""
    writer.line(f"public {abstract}class {simple}{extends} {{", klass.span)
    writer.indent()
    if info is not None and info.is_exception:
        writer.line("private static final long serialVersionUID = 1L;")
    for item in klass.fields:
        _field(item, writer, ctx)
    constructors = [method for method in klass.methods if method.is_constructor]
    if not constructors:
        _inherited_constructors(simple, info, writer, ctx)
    for method in klass.methods:
        writer.blank()
        _method(method, simple, writer, ctx)
    writer.dedent()
    writer.line("}")
    ctx.klass = None
    return writer


def _field(item: IRField, writer: CodeWriter, ctx: JavaContext) -> None:
    spelled = render_type(item.field_type, ctx)
    name = safe_identifier(item.name)
    if spelled is None:
        ctx.warn(
            "CW0697",
            f"field {item.name!r} has no known type; it is declared as Object",
            span=item.span,
            hint="annotate the field or the value assigned to it",
        )
        spelled = "Object"
    static = "static " if item.is_static else ""
    if item.default is not None:
        _enter(IRFunction("<field>"), ctx)
        value = emit_expression(item.default, ctx, item.field_type).text
        _leave(ctx)
        writer.line(f"public {static}{spelled} {name} = {value};", item.span)
    else:
        writer.line(f"public {static}{spelled} {name};", item.span)


def _inherited_constructors(
    simple: str, info: ClassInfo | None, writer: CodeWriter, ctx: JavaContext
) -> None:
    """Java does not inherit constructors: forward the base class's."""
    if info is None or ctx.index is None:
        return
    found = ctx.index.constructor(info)
    if found is not None:
        params = found[1].params
        writer.blank()
        signature = ", ".join(_param(param, ctx) for param in params)
        arguments = ", ".join(safe_identifier(param.name) for param in params)
        writer.line(f"public {simple}({signature}) {{")
        writer.indent()
        writer.line(f"super({arguments});")
        writer.dedent()
        writer.line("}")
        return
    if info.is_exception or info.builtin_base:
        writer.blank()
        writer.line(f"public {simple}() {{ super(); }}")
        writer.line(f"public {simple}(String message) {{ super(message); }}")


def _method(method: IRFunction, simple: str, writer: CodeWriter, ctx: JavaContext) -> None:
    _javadoc(writer, method.docstring)
    _decorators(writer, method)
    params = _params(method, ctx)
    if method.is_constructor:
        statements = list(method.body.statements)
        first: str | None = None
        index = next(
            (i for i, item in enumerate(statements) if _super_init(item) is not None), None
        )
        if index is not None:
            call = _super_init(statements[index])
            assert call is not None
            if index != 0:
                ctx.warn(
                    "CW0698",
                    "super().__init__() is not the first statement of __init__; Java runs it first",
                    span=method.span,
                    hint="move the call to the start of __init__",
                )
            statements.pop(index)
            _enter(method, ctx)
            info = ctx.klass
            base_params: list[IRParam] = []
            if info is not None and info.base and ctx.index is not None:
                found = ctx.index.constructor(ctx.index.classes[info.base])
                if found is not None:
                    base_params = found[1].params
            if base_params:
                arguments = lower_arguments(base_params, call, ctx, callee_name="__init__")
            else:
                arguments = []
                for item in call.args[:1]:
                    text = emit_expression(item, ctx).text
                    item_type = getattr(item, "value_type", None)
                    arguments.append(
                        text
                        if item_type is not None and item_type.name == "str"
                        else f"Py.str({text})"
                    )
            first = f"super({', '.join(arguments)});"
            pre = list(ctx.pre)
            _leave(ctx)
            if pre:
                first = None
                ctx.warn(
                    "CW0698",
                    "super().__init__() arguments need temporaries Java cannot place before super()",
                    span=method.span,
                )
        writer.line(f"public {simple}({params}) {{", method.span)
        if first is not None:
            writer.indent()
            writer.line(first)
            writer.dedent()
        _body(method, writer, ctx, IRBlock(statements))
        writer.line("}")
        return
    is_static = method.is_static or bool(method.meta.get("pythonClassMethod"))
    modifiers = "public static " if is_static else "public "
    returns = _return_type(method, ctx)
    name = safe_identifier(method.name)
    if method.name == "__str__":
        writer.line("@Override")
        returns = "String"
    if method.is_abstract:
        writer.line(f"{modifiers}abstract {returns} {name}({params});", method.span)
        return
    writer.line(f"{modifiers}{returns} {name}({params}) {{", method.span)
    _body(method, writer, ctx)
    writer.line("}")
