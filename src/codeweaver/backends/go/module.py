"""IR modules to Go files.

Three structural decisions, each forced by the language rather than chosen:

**Export requires renaming.** Go decides visibility by the first letter, so
``def total()`` must become ``Total`` for another package to call it. This is
the only target where CodeWeaver renames, and every rename is recorded on the
generated file so the migration report can list them.

**Classes become structs plus methods.** Go has no classes and no inheritance.
A Python class becomes a struct holding its fields and methods declared on a
pointer receiver — pointer, because Python objects have reference semantics and
a value receiver would mutate a copy. A base class is **embedded**, which gives
field and method promotion but not virtual dispatch: an overridden method is
not called through a base-typed value. That is a real behaviour change and is
reported, not glossed.

**Imports are collected, not declared.** Go rejects an unused import, so the
emitter records what it actually used while writing the body and emits the
import block afterwards.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import PurePosixPath
from typing import Any

from codeweaver.backends.common import CodeWriter
from codeweaver.backends.go.context import GoEmitContext
from codeweaver.backends.go.expressions import emit_expression, emit_params
from codeweaver.backends.go.naming import GO_POLICY, exported_name, unexported_name
from codeweaver.backends.go.statements import emit_block
from codeweaver.backends.go.types import render_type
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.ir.declarations import (
    ACCESSOR_GETTER,
    ACCESSOR_SETTER,
    IRClass,
    IRFunction,
    IRModule,
    Visibility,
)
from codeweaver.ir.expressions import IRName
from codeweaver.ir.statements import IRVarDecl
from codeweaver.ir.types import TypeKind

__all__ = [
    "GeneratedGoFile",
    "GoLayout",
    "generate_module",
    "output_path_for",
    "package_name_for",
]

_HEADER = (
    "// Generated by CodeWeaver from {source}.",
    "// Review before use: a successful build does not prove equivalent behaviour.",
)


def output_path_for(source_path: str) -> str:
    """The Go path for a Python source path.

    ``pkg/__init__.py`` becomes ``pkg/pkg.go`` rather than ``pkg/index.go``:
    Go has no special filename for a package, and naming the file after the
    package is the convention.
    """
    pure = PurePosixPath(source_path)
    stem = pure.parent.name or "main" if pure.stem == "__init__" else pure.stem
    return str(pure.with_name(f"{GO_POLICY.identifier(stem)}.go"))


def package_name_for(output_path: str) -> str:
    """The Go package a file in *output_path* belongs to.

    Go packages are directories, so every generated file in one directory
    shares a package name — which is the directory name, or ``main`` at the
    root.
    """
    parent = PurePosixPath(output_path).parent.name
    return unexported_name(parent) if parent else "main"


@dataclass
class GoLayout:
    """Where every module will be written, plus the Go module path."""

    paths: dict[str, str] = field(default_factory=dict)
    module_path: str = "codeweaver/output"

    @classmethod
    def for_modules(
        cls, modules: list[IRModule], *, module_path: str = "codeweaver/output"
    ) -> GoLayout:
        return cls(
            {module.name: output_path_for(module.path) for module in modules},
            module_path=module_path,
        )

    def import_path(self, module_name: str) -> str | None:
        """The Go import path for a project module, if it is in this layout."""
        path = self.paths.get(module_name)
        if path is None:
            return None
        directory = PurePosixPath(path).parent
        if str(directory) in ("", "."):
            return self.module_path
        return f"{self.module_path}/{directory}"


@dataclass
class GeneratedGoFile:
    """One generated Go file and what was learned generating it."""

    path: str
    source_path: str
    contents: str
    mappings: list[dict[str, Any]] = field(default_factory=list)
    diagnostics: DiagnosticBag = field(default_factory=DiagnosticBag)
    unsupported_count: int = 0
    #: source name -> Go name, for every name this file renamed.
    renames: dict[str, str] = field(default_factory=dict)

    @property
    def line_count(self) -> int:
        return self.contents.count("\n")

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "sourcePath": self.source_path,
            "lineCount": self.line_count,
            "unsupportedCount": self.unsupported_count,
            "renames": dict(sorted(self.renames.items())),
            "diagnostics": self.diagnostics.to_list(),
        }


def _build_renames(module: IRModule, ctx: GoEmitContext) -> dict[str, str]:
    """Map every top-level name this module declares onto its Go spelling."""
    renames: dict[str, str] = {}
    for function in module.functions:
        renames[function.name] = _go_name(function.name, function.visibility)
    for klass in module.classes:
        renames[klass.name] = _go_name(klass.name, klass.visibility)
    for statement in module.body:
        if isinstance(statement, IRVarDecl) and statement.name:
            visibility = Visibility.from_name(statement.name)
            renames[statement.name] = _go_name(statement.name, visibility)
    for imported in module.imports:
        for name in imported.names:
            renames[name.local_name] = exported_name(name.name)
    changed = {source: target for source, target in renames.items() if source != target}
    if changed:
        ctx.warn(
            "CW0730",
            f"{len(changed)} name(s) were renamed for Go visibility rules",
            hint="Go decides visibility by the first letter, so an exported "
            "name must be capitalised; the report lists every rename",
        )
    return renames


def _go_name(name: str, visibility: str) -> str:
    return unexported_name(name) if visibility != Visibility.PUBLIC else exported_name(name)


def generate_module(
    module: IRModule,
    layout: GoLayout | None = None,
    *,
    diagnostics: DiagnosticBag | None = None,
) -> GeneratedGoFile:
    """Generate the Go file for *module*."""
    layout = layout or GoLayout.for_modules([module])
    output_path = layout.paths.get(module.name) or output_path_for(module.path)
    ctx = GoEmitContext(
        source_path=module.path,
        output_path=output_path,
        package=package_name_for(output_path),
        diagnostics=diagnostics if diagnostics is not None else DiagnosticBag(),
    )
    ctx.renames = _build_renames(module, ctx)

    # The body is written first so that the import block can name exactly the
    # packages it turned out to need: Go rejects an unused import.
    body = CodeWriter(indent_text="\t")
    for statement in module.body:
        _emit_module_statement(statement, body, ctx)
    for klass in module.classes:
        body.blank()
        _emit_class(klass, body, ctx)
    for function in module.functions:
        body.blank()
        _emit_function(function, body, ctx)

    head = CodeWriter(indent_text="\t")
    for line in _HEADER:
        head.line(line.format(source=module.path or module.name))
    head.blank()
    if module.docstring:
        for line in module.docstring.strip().split("\n"):
            head.line(f"// {line}".rstrip())
    head.line(f"package {ctx.package}")
    _emit_imports(module, layout, head, ctx)

    contents = head.render()
    rendered_body = body.render()
    if rendered_body:
        contents = f"{contents}\n{rendered_body}"
    offset = head.line_count + 1
    mappings = [
        {**entry, "outputLine": entry["outputLine"] + offset} for entry in body.mapping_dict()
    ]
    return GeneratedGoFile(
        path=output_path,
        source_path=module.path,
        contents=contents,
        mappings=mappings,
        diagnostics=ctx.diagnostics,
        unsupported_count=len(ctx.gaps),
        renames={source: target for source, target in ctx.renames.items() if source != target},
    )


def _emit_imports(
    module: IRModule, layout: GoLayout, writer: CodeWriter, ctx: GoEmitContext
) -> None:
    from codeweaver.graph.dependency import resolve_relative_import

    paths: set[str] = set(ctx.imports)
    for imported in module.imports:
        absolute = resolve_relative_import(module.name, imported.module, imported.level)
        import_path = layout.import_path(absolute)
        if import_path is None:
            ctx.warn(
                "CW0731",
                f"import of {absolute or imported.module!r} is not a project module",
                span=imported.span,
                hint="find or re-implement the dependency in the Go ecosystem",
            )
            continue
        if import_path != layout.import_path(module.name):
            paths.add(import_path)
    if not paths:
        return
    writer.blank()
    if len(paths) == 1:
        writer.line(f'import "{next(iter(paths))}"')
        return
    writer.line("import (")
    writer.indent()
    for path in sorted(paths):
        writer.line(f'"{path}"')
    writer.dedent()
    writer.line(")")


def _emit_module_statement(statement, writer: CodeWriter, ctx: GoEmitContext) -> None:
    if not isinstance(statement, IRVarDecl):
        from codeweaver.backends.go.statements import emit_statement

        writer.blank()
        emit_statement(statement, writer, ctx)
        return
    name = ctx.rename(statement.name)
    keyword = "const" if statement.is_const else "var"
    rendered = (
        f" {render_type(statement.var_type)}"
        if statement.var_type.kind is not TypeKind.UNKNOWN
        else ""
    )
    writer.blank()
    if statement.value is None:
        writer.line(f"var {name}{rendered or ' any'}", statement.span)
        return
    value = emit_expression(statement.value, ctx).text
    writer.line(f"{keyword} {name}{rendered} = {value}", statement.span)


def _emit_class(klass: IRClass, writer: CodeWriter, ctx: GoEmitContext) -> None:
    name = ctx.rename(klass.name)
    if klass.docstring:
        for line in klass.docstring.strip().split("\n"):
            writer.line(f"// {line}".rstrip())
    if len(klass.bases) > 1:
        ctx.warn(
            "CW0732",
            f"struct {klass.name!r} has {len(klass.bases)} base classes; Go embeds only the first",
            span=klass.span,
        )
    writer.line(f"type {name} struct {{", klass.span)
    writer.indent()
    for base in klass.bases[:1]:
        if isinstance(base, IRName):
            ctx.warn(
                "CW0733",
                f"base class {base.name!r} is embedded, which promotes its fields "
                "and methods but gives no virtual dispatch",
                span=klass.span,
                hint="an overridden method is not called through a base-typed value",
            )
            writer.line(f"*{exported_name(base.name)}")
    for item in klass.fields:
        field_name = _go_name(item.name, item.visibility)
        writer.line(f"{field_name} {render_type(item.field_type)}", item.span)
    writer.dedent()
    writer.line("}")

    if klass.constructor is None:
        writer.blank()
        _emit_default_constructor(klass, writer, ctx)
    for method in klass.methods:
        writer.blank()
        _emit_method(klass, method, writer, ctx)


def _emit_method(
    klass: IRClass, method: IRFunction, writer: CodeWriter, ctx: GoEmitContext
) -> None:
    struct = ctx.rename(klass.name)
    receiver = GO_POLICY.identifier(
        str(method.meta.get("pythonReceiver", "")) or unexported_name(klass.name)[:1]
    )
    if method.is_constructor:
        _emit_constructor(klass, method, writer, ctx, receiver)
        return
    name = _method_name(method)
    if method.is_static:
        # Go has no static methods; a package-level function is the equivalent.
        ctx.warn(
            "CW0734",
            f"static method {method.name!r} becomes a package-level function",
            span=method.span,
        )
        _emit_function(method, writer, ctx, name_override=f"{struct}{name}")
        return
    previous = ctx.receiver
    ctx.receiver = receiver
    params = emit_params(method.params, ctx)
    result = _result(method, ctx)
    writer.line(f"func ({receiver} *{struct}) {name}({params}){result} {{", method.span)
    writer.indent()
    emit_block(method.body, writer, ctx)
    writer.dedent()
    writer.line("}")
    ctx.receiver = previous


def _method_name(method: IRFunction) -> str:
    """The Go method name, disambiguating property accessors.

    Go has no properties, so a getter/setter pair becomes two methods. They
    cannot share a name, so they get the ``Get``/``Set`` prefixes Go code uses
    by convention.
    """
    base = exported_name(method.name)
    if method.accessor == ACCESSOR_GETTER:
        return f"Get{base}"
    if method.accessor == ACCESSOR_SETTER:
        return f"Set{base}"
    return base


def _emit_constructor(
    klass: IRClass,
    method: IRFunction,
    writer: CodeWriter,
    ctx: GoEmitContext,
    receiver: str,
) -> None:
    """Emit ``__init__`` as a ``NewT`` constructor function.

    Go has no constructors. The convention is a package-level ``NewT`` that
    returns a pointer, which is also what the expression emitter generates for
    a class call.
    """
    struct = ctx.rename(klass.name)
    previous = ctx.receiver
    ctx.receiver = receiver
    params = emit_params(method.params, ctx)
    writer.line(f"func New{struct}({params}) *{struct} {{", method.span)
    writer.indent()
    writer.line(f"{receiver} := &{struct}{{}}")
    _emit_field_defaults(klass, receiver, writer, ctx)
    emit_block(method.body, writer, ctx)
    writer.line(f"return {receiver}")
    writer.dedent()
    writer.line("}")
    ctx.receiver = previous


def _emit_field_defaults(
    klass: IRClass, receiver: str, writer: CodeWriter, ctx: GoEmitContext
) -> None:
    """Assign the defaults Python declared on the class body.

    A Go struct field cannot have a default, so a class attribute's value would
    simply be lost.  Assigning it in the constructor is the faithful mapping;
    without it a translated object would silently start with a zero value.
    """
    for item in klass.fields:
        if item.default is None:
            continue
        name = _go_name(item.name, item.visibility)
        value = emit_expression(item.default, ctx).text
        writer.line(f"{receiver}.{name} = {value}", item.span)


def _emit_default_constructor(klass: IRClass, writer: CodeWriter, ctx: GoEmitContext) -> None:
    """Emit ``NewT`` for a class with no ``__init__``.

    The expression emitter turns a class call into ``NewT(...)``, so every
    struct needs one even when Python relied on the implicit constructor.
    """
    struct = ctx.rename(klass.name)
    receiver = unexported_name(klass.name)[:1] or "x"
    writer.line(f"func New{struct}() *{struct} {{", klass.span)
    writer.indent()
    writer.line(f"{receiver} := &{struct}{{}}")
    _emit_field_defaults(klass, receiver, writer, ctx)
    writer.line(f"return {receiver}")
    writer.dedent()
    writer.line("}")


def _emit_function(
    function: IRFunction,
    writer: CodeWriter,
    ctx: GoEmitContext,
    *,
    name_override: str = "",
) -> None:
    if function.docstring:
        for line in function.docstring.strip().split("\n"):
            writer.line(f"// {line}".rstrip())
    for decorator in function.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    if function.is_async:
        ctx.warn(
            "CW0735",
            f"async function {function.name!r} becomes an ordinary function; "
            "Go uses goroutines and channels instead",
            span=function.span,
            hint="callers will not await it",
        )
    name = name_override or ctx.rename(function.name)
    params = emit_params(function.params, ctx)
    result = _result(function, ctx)
    writer.line(f"func {name}({params}){result} {{", function.span)
    writer.indent()
    emit_block(function.body, writer, ctx)
    writer.dedent()
    writer.line("}")


def _result(function: IRFunction, ctx: GoEmitContext) -> str:  # noqa: ARG001
    """The result clause, empty when the function returns nothing."""
    if function.accessor == ACCESSOR_SETTER:
        return ""
    if function.return_type.kind is TypeKind.NONE:
        return ""
    if function.return_type.kind is TypeKind.UNKNOWN and not _returns_a_value(function):
        return ""
    return f" {render_type(function.return_type)}"


def _returns_a_value(function: IRFunction) -> bool:
    from codeweaver.ir.base import walk
    from codeweaver.ir.statements import IRReturn

    return any(
        isinstance(node, IRReturn) and node.value is not None for node in walk(function.body)
    )
