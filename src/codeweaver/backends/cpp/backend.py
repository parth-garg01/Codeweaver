"""The C++20 target backend and the project files it scaffolds.

The generated project is a CMake project:

* ``src/`` holds one header and one source file per Python module, plus the
  header-only runtime under ``src/cw_runtime/``;
* every module with an ``if __name__ == "__main__":`` block gets its own
  ``<module>.main.cpp`` and an executable target;
* the build defaults to ``Release`` (``-O3``), and ``-DCODEWEAVER_UNCHECKED=ON``
  removes bounds checks from indexing for maximum speed.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from typing import Any

from codeweaver.backends.common.files import GeneratedFile
from codeweaver.backends.cpp.context import RUNTIME_HEADER, SOURCE_ROOT, CppLayout
from codeweaver.backends.cpp.module import generate_module_files
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.project_index import ProjectIndex
from codeweaver.ir.declarations import IRModule

__all__ = ["CppBackend", "render_cmakelists", "runtime_header"]


def runtime_header() -> str:
    """The C++ runtime shipped with the generated project."""
    return (
        resources.files("codeweaver.backends.cpp")
        .joinpath("runtime/runtime.hpp")
        .read_text(encoding="utf-8")
    )


def _target_name(project_name: str) -> str:
    cleaned = (
        "".join(char if char.isalnum() else "_" for char in project_name) or "codeweaver_output"
    )
    return cleaned if not cleaned[0].isdigit() else f"p_{cleaned}"


def render_cmakelists(project_name: str, layout: CppLayout) -> str:
    target = _target_name(project_name)
    sources = sorted(f"{SOURCE_ROOT}/{layout.source(module)}" for module in layout.stems)
    lines = [
        "# Generated by CodeWeaver. Review before use.",
        "cmake_minimum_required(VERSION 3.20)",
        f"project({target} LANGUAGES CXX)",
        "",
        "set(CMAKE_CXX_STANDARD 20)",
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        "set(CMAKE_CXX_EXTENSIONS OFF)",
        "if(NOT CMAKE_BUILD_TYPE)",
        "  set(CMAKE_BUILD_TYPE Release)",
        "endif()",
        "",
        'option(CODEWEAVER_UNCHECKED "Skip bounds checks on indexing (faster, no IndexError)" OFF)',
        "",
        f"add_library({target}_lib STATIC",
        *(f"  {source}" for source in sources),
        ")",
        f"target_include_directories({target}_lib PUBLIC {SOURCE_ROOT})",
        "if(CODEWEAVER_UNCHECKED)",
        f"  target_compile_definitions({target}_lib PUBLIC CW_UNCHECKED)",
        "endif()",
    ]
    for module in sorted(layout.entry_modules):
        executable = _target_name(module.replace(".", "_"))
        lines += [
            "",
            f"add_executable({executable} {SOURCE_ROOT}/{layout.main_source(module)})",
            f"target_link_libraries({executable} PRIVATE {target}_lib)",
        ]
    return "\n".join(lines) + "\n"


@dataclass
class CppBackend:
    """Backend adapter registered in the language registry."""

    language: str = "cpp"
    display_name: str = "C++20"
    file_extension: str = ".cpp"
    supported_constructs: tuple[str, ...] = field(
        default_factory=lambda: (
            "modules as namespaces with a header and a source file each",
            "classes with single inheritance, fields, methods, properties and static members",
            "constructors with super().__init__ in the initialiser list",
            "virtual dispatch only for methods that are actually overridden",
            "exceptions mapped onto a C++ copy of Python's builtin hierarchy",
            "try/except/else/finally with exact else and finally semantics",
            "for/else and while/else with exact semantics",
            "keyword arguments matched to the callee's signature",
            "Python semantics for /, //, %, ** and negative indexing",
            "list, set and insertion-ordered dict literals and comprehensions",
            "f-strings, str() and print() with Python's formatting",
            "builtins: len, print, str, int, float, bool, abs, round, min, max, sum, sorted, list, set, range, isinstance, any, all",
            "str, list, dict and set methods via an inline runtime",
            "math module functions and constants",
            "if __name__ == '__main__' blocks as program entry points",
        )
    )
    known_limitations: tuple[str, ...] = field(
        default_factory=lambda: (
            "int is a 64-bit integer; Python's arbitrary precision is not modelled",
            "lists, dicts and sets have value semantics: assigning one to a second name copies it",
            "parameters without annotations become template parameters",
            "async/await, generators, with, match and nested functions are reported, not translated",
            "module-level statements other than declarations are not executed at start-up",
            "multiple inheritance keeps only the first base class",
            "isinstance against builtin types is decided at compile time",
        )
    )
    required_toolchains: tuple[str, ...] = field(default_factory=lambda: ("c++",))
    uses_type_inference: bool = True

    def create_layout(self, modules: list[IRModule], index: Any = None) -> CppLayout:
        project = index if isinstance(index, ProjectIndex) else ProjectIndex.build(modules)
        return CppLayout.build(modules, project)

    def generate_files(
        self,
        module: IRModule,
        layout: CppLayout,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> list[GeneratedFile]:
        return generate_module_files(module, layout, diagnostics=diagnostics)

    def generate_module(
        self,
        module: IRModule,
        layout: CppLayout | None = None,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> GeneratedFile:
        """The module's header (the registry protocol's single-file view)."""
        layout = layout or self.create_layout([module])
        return self.generate_files(module, layout, diagnostics=diagnostics)[0]

    def project_files(self, project_name: str, layout: CppLayout) -> dict[str, str]:
        return {
            "CMakeLists.txt": render_cmakelists(project_name, layout),
            f"{SOURCE_ROOT}/{RUNTIME_HEADER}": runtime_header(),
        }
