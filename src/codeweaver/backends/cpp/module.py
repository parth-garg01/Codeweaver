"""IR modules to a C++ header and source file.

Each Python module becomes a namespace (``pkg.models`` -> ``pkg::models``) with
a header holding declarations and a source file holding definitions.  The
header is ordered so that import cycles still compile:

1. forward declarations of this module's classes and of every class it
   imports, so any class can be named before anything is defined;
2. type aliases and using-declarations for imported classes;
3. ``extern`` module variables and function prototypes;
4. ``#include`` of the imported modules' headers;
5. using-declarations for imported functions and variables;
6. class definitions;
7. definitions of functions that must be visible to callers (generic ones).

Methods are virtual only when the project index shows they are overridden or
override something; every other call is direct and inlinable.
"""

from __future__ import annotations

from codeweaver.backends.common.analysis import (
    escaping_loop_variables,
    is_main_guard,
    local_names,
    rebound_names,
)
from codeweaver.backends.common.files import GeneratedFile
from codeweaver.backends.common.writer import CodeWriter
from codeweaver.backends.cpp.context import RUNTIME_HEADER, CppContext, CppLayout
from codeweaver.backends.cpp.expressions import emit_expression, lower_arguments
from codeweaver.backends.cpp.naming import safe_identifier
from codeweaver.backends.cpp.statements import emit_statement, is_super_init
from codeweaver.backends.cpp.types import render_type
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.dependency import resolve_relative_import
from codeweaver.graph.project_index import ClassInfo, ScopeKind
from codeweaver.ir.base import walk
from codeweaver.ir.declarations import IRClass, IRField, IRFunction, IRModule, Visibility
from codeweaver.ir.expressions import IRParam
from codeweaver.ir.statements import IRBlock, IRReturn, IRThrow, IRVarDecl
from codeweaver.ir.types import IRType, TypeKind

__all__ = ["generate_module_files"]

_HEADER = (
    "// Generated by CodeWeaver from {source}.",
    "// Review before use: a successful compile does not prove equivalent behaviour.",
)


def _header_lines(writer: CodeWriter, module: IRModule) -> None:
    for line in _HEADER:
        writer.line(line.format(source=module.path or module.name))


def _doc(writer: CodeWriter, text: str) -> None:
    if not text:
        return
    writer.line("/**")
    for line in text.strip().split("\n"):
        writer.line(f" * {line}".rstrip())
    writer.line(" */")


# ----------------------------------------------------------------- signatures


def _is_generic(function: IRFunction, ctx: CppContext) -> bool:
    """A function with an unknown parameter or return type becomes a template."""
    for param in function.params:
        if param.style in ("var_keyword",):
            continue
        if render_type(param.param_type, ctx) is None:
            return True
    if function.is_constructor:
        return False
    return render_type(function.return_type, ctx, returning=True) is None


def _param_text(
    param: IRParam, function: IRFunction, ctx: CppContext, *, with_default: bool
) -> str:
    name = safe_identifier(param.name)
    layout = ctx.layout
    mutated = layout.mutability.of(function) if layout is not None else set()
    rebound = param.name in rebound_names(function)
    if param.style == "var_positional":
        element = render_type(param.param_type, ctx)
        spelled = f"std::vector<{element}>" if element else None
        return f"const {spelled}& {name}" if spelled else f"const auto& {name}"
    if param.style == "var_keyword":
        ctx.warn("CW0692", f"**{param.name} is not translated to C++", span=param.span)
        return f"const cw::dict<std::string, std::string>& {name} = {{}}"
    spelled = render_type(param.param_type, ctx)
    if spelled is None:
        if param.param_type.kind is TypeKind.UNKNOWN:
            ctx.warn(
                "CW0693",
                f"parameter {param.name!r} has no type annotation; it becomes a template parameter",
                span=param.span,
                hint="annotate it so the function can be compiled once, out of line",
            )
        base = "auto" if rebound else "auto&" if param.name in mutated else "const auto&"
        text = f"{base} {name}"
    elif _passed_by_value(param.param_type) or rebound:
        text = f"{spelled} {name}"
    elif param.name in mutated:
        text = f"{spelled}& {name}"
    else:
        text = f"const {spelled}& {name}"
    if with_default and param.default is not None:
        text += f" = {emit_expression(param.default, ctx, param.param_type).text}"
    return text


def _passed_by_value(ir_type: IRType) -> bool:
    if ir_type.kind is TypeKind.PRIMITIVE and ir_type.name in ("int", "float", "bool"):
        return True
    if ir_type.kind is TypeKind.OPTIONAL and ir_type.args:
        inner = ir_type.args[0]
        return inner.kind is TypeKind.PRIMITIVE and inner.name in ("int", "float", "bool")
    return False


def _params(function: IRFunction, ctx: CppContext, *, with_default: bool) -> str:
    return ", ".join(
        _param_text(param, function, ctx, with_default=with_default) for param in function.params
    )


def _return_text(function: IRFunction, ctx: CppContext) -> str:
    spelled = render_type(function.return_type, ctx, returning=True)
    if function.is_async:
        ctx.warn(
            "CW0694",
            f"async function {function.name!r} is generated as a synchronous function",
            span=function.span,
        )
    return spelled or "auto"


# --------------------------------------------------------------------- entry


def generate_module_files(
    module: IRModule, layout: CppLayout, *, diagnostics: DiagnosticBag | None = None
) -> list[GeneratedFile]:
    ctx = CppContext(
        source_path=module.path,
        output_path=layout.header(module.name),
        diagnostics=diagnostics if diagnostics is not None else DiagnosticBag(),
        layout=layout,
        index=layout.index,
        module=module,
    )
    header = _emit_header(module, layout, ctx)
    source = _emit_source(module, layout, ctx)
    from codeweaver.backends.cpp.context import SOURCE_ROOT

    files = [
        GeneratedFile(
            path=f"{SOURCE_ROOT}/{layout.header(module.name)}",
            source_path=module.path,
            contents=header.render(),
            mappings=header.mapping_dict(),
            diagnostics=ctx.diagnostics,
            unsupported_count=len(ctx.gaps),
        ),
        GeneratedFile(
            path=f"{SOURCE_ROOT}/{layout.source(module.name)}",
            source_path=module.path,
            contents=source.render(),
            mappings=source.mapping_dict(),
            diagnostics=ctx.diagnostics,
        ),
    ]
    if module.name in layout.entry_modules:
        main = _emit_main(module, layout, ctx)
        files.append(
            GeneratedFile(
                path=f"{SOURCE_ROOT}/{layout.main_source(module.name)}",
                source_path=module.path,
                contents=main.render(),
                mappings=main.mapping_dict(),
                diagnostics=ctx.diagnostics,
            )
        )
    return files


# -------------------------------------------------------------------- header


def _imports(module: IRModule, ctx: CppContext) -> list[str]:
    """Project modules this module imports, in source order, without repeats."""
    found: list[str] = []
    for imported in module.imports:
        absolute = resolve_relative_import(module.name, imported.module, imported.level)
        candidates = [absolute]
        if not imported.imports_whole_module:
            candidates += [f"{absolute}.{name.name}" for name in imported.names]
        for candidate in candidates:
            if (
                ctx.index is not None
                and candidate in ctx.index.modules
                and candidate not in found
                and candidate != module.name
            ):
                found.append(candidate)
    return found


def _emit_header(module: IRModule, layout: CppLayout, ctx: CppContext) -> CodeWriter:
    writer = CodeWriter()
    _header_lines(writer, module)
    writer.line("#pragma once")
    writer.blank()
    writer.line(f'#include "{RUNTIME_HEADER}"')
    index = layout.index
    namespace = ctx.namespace
    imports = _imports(module, ctx)
    scope = index.scopes.get(module.name, {})

    # 1. forward declarations
    writer.blank()
    _forward_declarations(writer, module.name, [klass.name for klass in module.classes], index)
    imported_classes: dict[str, list[str]] = {}
    for _local, entry in sorted(scope.items()):
        if entry.kind is ScopeKind.CLASS and entry.module != module.name:
            imported_classes.setdefault(entry.module, [])
            if entry.name not in imported_classes[entry.module]:
                imported_classes[entry.module].append(entry.name)
        if entry.kind is ScopeKind.MODULE:
            imported_classes.setdefault(entry.qualified, [])
    for other, names in sorted(imported_classes.items()):
        _forward_declarations(writer, other, names, index)

    writer.blank()
    writer.line(f"namespace {namespace} {{")
    writer.line("using namespace std::string_literals;")
    # 2. imported classes and module aliases
    for local, entry in sorted(scope.items()):
        if entry.module == module.name:
            continue
        if entry.kind is ScopeKind.CLASS:
            qualified = ctx.qualified(entry.module, entry.name)
            if local == entry.name:
                writer.line(f"using {qualified};")
            else:
                writer.line(f"using {safe_identifier(local)} = {qualified};")
        elif entry.kind is ScopeKind.MODULE:
            writer.line(
                f"namespace {safe_identifier(local)} = ::{CppLayout.namespace(entry.qualified)};"
            )
        elif entry.kind is ScopeKind.EXTERNAL:
            writer.line(f"// external import {entry.qualified!s} has no C++ counterpart")
    # 3. variables and prototypes
    for statement in module.body:
        if isinstance(statement, IRVarDecl):
            spelled = render_type(statement.var_type, ctx)
            if spelled is None:
                ctx.warn(
                    "CW0695",
                    f"module variable {statement.name!r} has an unknown type",
                    span=statement.span,
                )
                continue
            const = "const " if statement.is_const else ""
            writer.line(
                f"extern {const}{spelled} {safe_identifier(statement.name)};", statement.span
            )
    for function in module.functions:
        if _is_generic(function, ctx):
            continue
        _doc(writer, function.docstring)
        writer.line(
            f"{_return_text(function, ctx)} {safe_identifier(function.name)}({_params(function, ctx, with_default=True)});",
            function.span,
        )
    writer.line(f"}}  // namespace {namespace}")

    # 4. includes
    if imports:
        writer.blank()
        for other in imports:
            writer.line(f'#include "{layout.header(other)}"')

    writer.blank()
    writer.line(f"namespace {namespace} {{")
    # 5. imported functions and variables
    for local, entry in sorted(scope.items()):
        if entry.module == module.name or entry.kind not in (
            ScopeKind.FUNCTION,
            ScopeKind.VARIABLE,
        ):
            continue
        if local == entry.name:
            writer.line(f"using {ctx.qualified(entry.module, entry.name)};")
    # 6. classes, base classes first so a subclass in the same module compiles
    for klass in _base_first(module.classes, module.name, ctx):
        writer.blank()
        _emit_class(klass, writer, ctx)
    # 7. generic functions are defined where every caller can see them
    for function in module.functions:
        if _is_generic(function, ctx):
            writer.blank()
            _emit_function_definition(function, writer, ctx, inline=True)
    writer.line(f"}}  // namespace {namespace}")
    return writer


def _forward_declarations(writer: CodeWriter, module: str, classes: list[str], index) -> None:
    namespace = CppLayout.namespace(module)
    writer.line(f"namespace {namespace} {{")
    for name in classes:
        info = index.classes.get(f"{module}.{name}")
        writer.line(f"class {safe_identifier(name)};")
        del info
    writer.line(f"}}  // namespace {namespace}")


def _base_first(classes: list[IRClass], module: str, ctx: CppContext) -> list[IRClass]:
    ordered: list[IRClass] = []
    by_name = {klass.name: klass for klass in classes}
    visiting: set[str] = set()

    def visit(klass: IRClass) -> None:
        if klass in ordered or klass.name in visiting:
            return
        visiting.add(klass.name)
        info = ctx.index.classes.get(f"{module}.{klass.name}") if ctx.index else None
        if info is not None and info.base.startswith(f"{module}."):
            base = by_name.get(info.base[len(module) + 1 :])
            if base is not None:
                visit(base)
        ordered.append(klass)

    for klass in classes:
        visit(klass)
    return ordered


def _base_clause(info: ClassInfo | None, ctx: CppContext) -> str:
    if info is None:
        return "cw::Object"
    if info.base and ctx.index is not None and info.base in ctx.index.classes:
        return ctx.class_spelling(ctx.index.classes[info.base])
    if info.builtin_base:
        return f"cw::{info.builtin_base}"
    return "cw::Object"


def _emit_class(klass: IRClass, writer: CodeWriter, ctx: CppContext) -> None:
    info = ctx.own_class(klass)
    ctx.klass = info
    _doc(writer, klass.docstring)
    if len(klass.bases) > 1:
        ctx.warn(
            "CW0696",
            f"class {klass.name!r} has {len(klass.bases)} base classes; only the first project or exception base is used",
            span=klass.span,
        )
    for decorator in klass.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    final = ""
    if info is not None and not info.subclasses and not info.is_abstract:
        final = " final"
    base = _base_clause(info, ctx)
    writer.line(f"class {safe_identifier(klass.name)}{final} : public {base} {{", klass.span)
    writer.line(" public:")
    writer.indent()
    for item in klass.fields:
        _emit_field(item, writer, ctx)
    if klass.fields:
        writer.blank()
    has_constructor = any(method.is_constructor for method in klass.methods)
    if not has_constructor and info is not None and (info.base or info.builtin_base):
        writer.line(f"using {base}::{base.rsplit('::', 1)[-1]};")
    for method in klass.methods:
        _emit_method_declaration(method, klass, writer, ctx)
    private = [item for item in klass.fields if item.visibility == Visibility.PRIVATE]
    del private
    writer.dedent()
    writer.line("};")
    ctx.klass = None


def _emit_field(item: IRField, writer: CodeWriter, ctx: CppContext) -> None:
    spelled = render_type(item.field_type, ctx)
    name = safe_identifier(item.name)
    if spelled is None:
        marker = ctx.gap(
            "AnnAssign",
            f"field {item.name!r} has no known type and cannot be declared in C++",
            item.span,
            "annotate the field or the value assigned to it",
        )
        writer.line(marker, item.span)
        return
    static = "static inline " if item.is_static else ""
    if item.default is not None:
        value = emit_expression(item.default, ctx, item.field_type).text
        writer.line(f"{static}{spelled} {name} = {value};", item.span)
    else:
        writer.line(f"{static}{spelled} {name}{{}};", item.span)


def _method_modifiers(method: IRFunction, ctx: CppContext) -> tuple[str, str]:
    info = ctx.klass
    if method.is_static or method.meta.get("pythonClassMethod"):
        return "static ", ""
    if method.is_constructor or info is None or ctx.index is None:
        return "", ""
    prefix = ""
    suffix = ""
    if ctx.index.needs_dispatch(info, method.name):
        if ctx.index.overrides(info, method.name):
            suffix = " override"
        else:
            prefix = "virtual "
    return prefix, suffix


def _emit_method_declaration(
    method: IRFunction, klass: IRClass, writer: CodeWriter, ctx: CppContext
) -> None:
    _doc(writer, method.docstring)
    for decorator in method.decorators:
        text = decorator.source_text.lstrip("@")
        if text not in ("staticmethod", "classmethod", "property", "abstractmethod"):
            writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    generic = _is_generic(method, ctx)
    prefix, suffix = _method_modifiers(method, ctx)
    if generic and (prefix or suffix):
        ctx.warn(
            "CW0697",
            f"method {method.name!r} is overridden but has unannotated parameters; templates cannot be virtual",
            span=method.span,
            hint="annotate its parameters",
        )
        prefix, suffix = "", ""
    params = _params(method, ctx, with_default=True)
    if method.is_constructor:
        explicit = "explicit " if len(method.params) == 1 else ""
        signature = f"{explicit}{safe_identifier(klass.name)}({params})"
    else:
        signature = f"{prefix}{_return_text(method, ctx)} {safe_identifier(method.name)}({params})"
    if method.is_abstract:
        writer.line(f"{signature}{suffix} = 0;", method.span)
        return
    if generic:
        writer.line(f"{signature}{suffix} {{", method.span)
        writer.indent()
        _emit_body(method, writer, ctx)
        writer.dedent()
        writer.line("}")
        return
    writer.line(f"{signature}{suffix};", method.span)


# -------------------------------------------------------------------- source


def _emit_source(module: IRModule, layout: CppLayout, ctx: CppContext) -> CodeWriter:
    writer = CodeWriter()
    _header_lines(writer, module)
    writer.line(f'#include "{layout.header(module.name)}"')
    writer.blank()
    writer.line(f"namespace {ctx.namespace} {{")
    for statement in module.body:
        if isinstance(statement, IRVarDecl):
            spelled = render_type(statement.var_type, ctx)
            if spelled is None:
                continue
            const = "const " if statement.is_const else ""
            if statement.value is None:
                writer.line(
                    f"{const}{spelled} {safe_identifier(statement.name)}{{}};", statement.span
                )
            else:
                value = emit_expression(statement.value, ctx, statement.var_type).text
                writer.line(
                    f"{const}{spelled} {safe_identifier(statement.name)} = {value};", statement.span
                )
        elif (
            is_main_guard(statement)
            or statement.kind in ("comment", "noop")
            or statement.kind == "expression_statement"
            and _is_docstring_like(statement)
        ):
            continue
        else:
            writer.line(
                ctx.gap(
                    statement.kind,
                    "module-level statements run at import time in Python and are not executed in C++",
                    statement.span,
                    "move the code into a function, or into the __main__ block",
                ),
                statement.span,
            )
    for klass in module.classes:
        info = ctx.own_class(klass)
        ctx.klass = info
        for method in klass.methods:
            if method.is_abstract or _is_generic(method, ctx):
                continue
            writer.blank()
            _emit_method_definition(method, klass, writer, ctx)
        ctx.klass = None
    for function in module.functions:
        if _is_generic(function, ctx):
            continue
        writer.blank()
        _emit_function_definition(function, writer, ctx, inline=False)
    writer.line(f"}}  // namespace {ctx.namespace}")
    return writer


def _is_docstring_like(statement) -> bool:
    expression = getattr(statement, "expression", None)
    return getattr(expression, "kind", "") == "literal" and isinstance(
        getattr(expression, "value", None), str
    )


def _enter_function(function: IRFunction, ctx: CppContext) -> None:
    ctx.function = function
    ctx.locals = local_names(function)
    receiver = str(function.meta.get("pythonReceiver", ""))
    ctx.receiver = "" if function.meta.get("pythonClassMethod") else receiver
    ctx.class_receiver = receiver if function.meta.get("pythonClassMethod") else ""
    ctx.locals.discard(receiver)
    ctx.in_constructor = function.is_constructor
    ctx.escaping = escaping_loop_variables(function.body)
    ctx.declared = {
        node.name for node in walk(function.body) if isinstance(node, IRVarDecl)
    } & ctx.escaping


def _leave_function(ctx: CppContext) -> None:
    ctx.function = None
    ctx.locals = set()
    ctx.receiver = ""
    ctx.class_receiver = ""
    ctx.in_constructor = False
    ctx.escaping = set()
    ctx.declared = set()


def _emit_body(
    function: IRFunction, writer: CodeWriter, ctx: CppContext, body: IRBlock | None = None
) -> None:
    _enter_function(function, ctx)
    block = body if body is not None else function.body
    if block.is_empty:
        writer.line("// pass")
    for statement in block.statements:
        emit_statement(statement, writer, ctx)
    if _needs_fallthrough_guard(function, block, ctx):
        # Python would return None here; the C++ return type has no None.
        writer.line('throw cw::TypeError("function ended without returning a value");')
    _leave_function(ctx)


def _needs_fallthrough_guard(function: IRFunction, block: IRBlock, ctx: CppContext) -> bool:
    if function.is_constructor or function.name == "__main__":
        return False
    spelled = render_type(function.return_type, ctx, returning=True)
    if spelled in (None, "void", "auto"):
        return False
    last = block.statements[-1] if block.statements else None
    return not isinstance(last, IRReturn | IRThrow)


def _emit_function_definition(
    function: IRFunction, writer: CodeWriter, ctx: CppContext, *, inline: bool
) -> None:
    for decorator in function.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    if inline:
        _doc(writer, function.docstring)
    params = _params(function, ctx, with_default=inline)
    prefix = "inline " if inline else ""
    writer.line(
        f"{prefix}{_return_text(function, ctx)} {safe_identifier(function.name)}({params}) {{",
        function.span,
    )
    writer.indent()
    _emit_body(function, writer, ctx)
    writer.dedent()
    writer.line("}")


def _emit_method_definition(
    method: IRFunction, klass: IRClass, writer: CodeWriter, ctx: CppContext
) -> None:
    class_name = safe_identifier(klass.name)
    params = _params(method, ctx, with_default=False)
    if method.is_constructor:
        statements = list(method.body.statements)
        initialiser = ""
        if statements and is_super_init(statements[0]) is not None:
            call = is_super_init(statements[0])
            assert call is not None
            info = ctx.klass
            base = _base_clause(info, ctx)
            base_params: list[IRParam] = []
            if info is not None and info.base and ctx.index is not None:
                found = ctx.index.constructor(ctx.index.classes[info.base])
                if found is not None:
                    base_params = found[1].params
            _enter_function(method, ctx)
            if base_params:
                args = lower_arguments(
                    base_params, call, ctx, callee_name="__init__", module_of_callee=""
                )
            else:
                args = [emit_expression(item, ctx).text for item in call.args]
            initialiser = f" : {base}({', '.join(args)})"
            statements = statements[1:]
        elif any(is_super_init(statement) is not None for statement in statements):
            ctx.warn(
                "CW0698",
                "super().__init__() is not the first statement of __init__; C++ initialises the base first",
                span=method.span,
                hint="move the call to the start of __init__",
            )
        writer.line(f"{class_name}::{class_name}({params}){initialiser} {{", method.span)
        writer.indent()
        _emit_body(method, writer, ctx, IRBlock(statements))
        writer.dedent()
        writer.line("}")
        return
    writer.line(
        f"{_return_text(method, ctx)} {class_name}::{safe_identifier(method.name)}({params}) {{",
        method.span,
    )
    writer.indent()
    _emit_body(method, writer, ctx)
    writer.dedent()
    writer.line("}")


# ---------------------------------------------------------------------- main


def _emit_main(module: IRModule, layout: CppLayout, ctx: CppContext) -> CodeWriter:
    writer = CodeWriter()
    _header_lines(writer, module)
    writer.line(f'#include "{layout.header(module.name)}"')
    writer.blank()
    writer.line("int main() {")
    writer.indent()
    writer.line("return cw::run_main([] {")
    writer.indent()
    writer.line(f"using namespace ::{ctx.namespace};")
    writer.line("using namespace std::string_literals;")
    guard = next(statement for statement in module.body if is_main_guard(statement))
    fake = IRFunction("__main__", body=guard.then_body)  # type: ignore[attr-defined]
    _enter_function(fake, ctx)
    for statement in guard.then_body.statements:  # type: ignore[attr-defined]
        emit_statement(statement, writer, ctx)
    _leave_function(ctx)
    writer.dedent()
    writer.line("});")
    writer.dedent()
    writer.line("}")
    return writer
