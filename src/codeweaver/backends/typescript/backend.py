"""The TypeScript target backend and the project files it scaffolds.

The generated output is a standalone TypeScript project: sources plus a
``tsconfig.json`` and a ``package.json``.  Both are written with `strict` type
checking on, because the point of validating with ``tsc`` is to find the places
where the translation lost information, and a loose configuration would hide
exactly those places.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

from codeweaver.backends.typescript.module import (
    GeneratedFile,
    ModuleLayout,
    generate_module,
    output_path_for,
)
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.ir.declarations import IRModule

__all__ = ["TypeScriptBackend", "project_files", "render_package_json", "render_tsconfig"]

_TSCONFIG: dict[str, Any] = {
    "compilerOptions": {
        "target": "ES2022",
        "module": "ES2022",
        "moduleResolution": "bundler",
        "strict": True,
        "noImplicitAny": True,
        "noUncheckedIndexedAccess": True,
        "forceConsistentCasingInFileNames": True,
        "skipLibCheck": True,
        "noEmit": True,
        "declaration": False,
        "lib": ["ES2022"],
    },
    "include": ["**/*.ts"],
}


def render_tsconfig(*, strict: bool = True) -> str:
    """Render ``tsconfig.json`` deterministically."""
    config = json.loads(json.dumps(_TSCONFIG))
    if not strict:
        config["compilerOptions"]["strict"] = False
        config["compilerOptions"]["noImplicitAny"] = False
        config["compilerOptions"]["noUncheckedIndexedAccess"] = False
    return json.dumps(config, indent=2, sort_keys=True) + "\n"


def render_package_json(name: str, version: str = "0.0.0") -> str:
    """Render a minimal ``package.json`` for the generated project."""
    payload = {
        "name": name or "codeweaver-output",
        "version": version or "0.0.0",
        "private": True,
        "type": "module",
        "description": "Generated by CodeWeaver. Review before use.",
        "scripts": {"typecheck": "tsc --noEmit"},
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def project_files(project_name: str, *, strict: bool = True) -> dict[str, str]:
    """The non-source files a generated TypeScript project needs."""
    return {
        "tsconfig.json": render_tsconfig(strict=strict),
        "package.json": render_package_json(project_name),
    }


@dataclass
class TypeScriptBackend:
    """Backend adapter registered in the language registry."""

    language: str = "typescript"
    display_name: str = "TypeScript 5"
    file_extension: str = ".ts"
    strict: bool = True
    supported_constructs: tuple[str, ...] = field(
        default_factory=lambda: (
            "modules with relative ESM imports",
            "exported constants, functions and classes",
            "classes with single inheritance, fields, methods and getters",
            "constructors, including super() delegation",
            "async functions returning Promise<T>",
            "parameters with types, defaults and rest parameters",
            "arithmetic, bitwise, logical and strict comparison operators",
            "floor division lowered to Math.floor",
            "template literals from f-strings",
            "array, tuple, Set and object literals",
            "if/else-if chains, while, for-of and counted for loops",
            "try/catch with instanceof dispatch, finally, throw",
            "assertions lowered to guarded throws",
        )
    )
    known_limitations: tuple[str, ...] = field(
        default_factory=lambda: (
            "keyword arguments become a trailing options object, which the callee must accept",
            "while/else and for/else bodies are reported, not emitted",
            "try/else bodies move inside the try block and become catchable",
            "deleting a binding (del x) has no equivalent",
            "stepped slices have no equivalent",
            "multiple inheritance keeps only the first base class",
            "decorators are recorded as comments, not applied",
            "integer arithmetic becomes IEEE-754 double arithmetic",
        )
    )
    required_toolchains: tuple[str, ...] = field(default_factory=lambda: ("tsc",))

    def generate_module(
        self,
        module: IRModule,
        layout: ModuleLayout | None = None,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> GeneratedFile:
        return generate_module(module, layout, diagnostics=diagnostics)

    def generate_project(
        self,
        modules: list[IRModule],
        *,
        project_name: str = "codeweaver-output",
        diagnostics: DiagnosticBag | None = None,
    ) -> dict[str, str]:
        """Generate every file of the target project, keyed by output path.

        Modules are generated in name order so the output is reproducible, and
        the layout is computed up front so every relative import can be
        resolved even in the presence of dependency cycles.
        """
        layout = ModuleLayout.for_modules(modules)
        files = project_files(project_name, strict=self.strict)
        for module in sorted(modules, key=lambda item: item.name):
            generated = self.generate_module(module, layout, diagnostics=diagnostics)
            files[generated.path] = generated.contents
        return files

    def output_path(self, source_path: str) -> str:
        return output_path_for(source_path)
