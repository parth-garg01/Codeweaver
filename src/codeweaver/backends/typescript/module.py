"""IR modules to TypeScript files.

Import specifiers are the fiddly part.  Python resolves ``from pkg.models
import Account`` through its module search path; TypeScript resolves
``./models`` relative to the importing file.  The backend therefore needs to
know every module in the project up front, which is what :class:`ModuleLayout`
carries.  An import it cannot resolve to a project module is emitted with the
original dotted name and reported, so the generated file fails to compile in an
obvious place rather than importing something unintended.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import PurePosixPath
from typing import Any

from codeweaver.backends.common.writer import CodeWriter
from codeweaver.backends.typescript.context import EmitContext
from codeweaver.backends.typescript.exceptions import (
    is_builtin_exception,
    map_exception_name,
)
from codeweaver.backends.typescript.expressions import emit_expression, emit_params
from codeweaver.backends.typescript.naming import safe_identifier, safe_property
from codeweaver.backends.typescript.statements import emit_block, emit_statement
from codeweaver.backends.typescript.types import render_return_type, render_type
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.ir.declarations import (
    ACCESSOR_GETTER,
    ACCESSOR_SETTER,
    IRClass,
    IRFunction,
    IRImport,
    IRModule,
    Visibility,
)
from codeweaver.ir.expressions import IRName
from codeweaver.ir.statements import IRVarDecl
from codeweaver.ir.types import TypeKind

__all__ = [
    "JAVASCRIPT",
    "TYPESCRIPT",
    "Dialect",
    "GeneratedFile",
    "ModuleLayout",
    "generate_module",
    "output_path_for",
]

#: Decorators the backend turns into a TypeScript modifier, so repeating them
#: as a "not applied" comment would be misleading.
_HANDLED_DECORATORS = frozenset({"staticmethod", "property", "abstractmethod"})

#: Generated header.  It names the source file so a reviewer can find the
#: original, and states plainly that the translation is unverified.
_HEADER = (
    "// Generated by CodeWeaver from {source}.",
    "// Review before use: a successful compile does not prove equivalent behaviour.",
)


@dataclass(frozen=True, slots=True)
class Dialect:
    """One ECMAScript dialect: a file extension and whether it has types.

    As far as code generation is concerned, TypeScript and JavaScript differ in
    exactly these two respects — which is why they share an emitter rather than
    keeping two copies of operator precedence, statement shapes, builtin
    mapping and exception mapping that could drift apart.
    """

    name: str
    extension: str
    emit_types: bool


#: The dialects this emitter produces.
TYPESCRIPT = Dialect("typescript", ".ts", True)
JAVASCRIPT = Dialect("javascript", ".js", False)


def output_path_for(source_path: str, *, extension: str = ".ts") -> str:
    """The output path for a Python source path.

    ``__init__.py`` becomes ``index`` because that is the filename both Node and
    bundlers resolve for a directory import.
    """
    pure = PurePosixPath(source_path)
    stem = "index" if pure.stem == "__init__" else pure.stem
    return str(pure.with_name(f"{stem}{extension}"))


@dataclass
class ModuleLayout:
    """Where every project module will be written."""

    #: dotted module name -> output path
    paths: dict[str, str] = field(default_factory=dict)

    @classmethod
    def for_modules(
        cls, modules: list[IRModule], *, dialect: Dialect | None = None
    ) -> ModuleLayout:
        extension = (dialect or TYPESCRIPT).extension
        return cls(
            {module.name: output_path_for(module.path, extension=extension) for module in modules}
        )

    def specifier(self, from_module: str, to_module: str) -> str | None:
        """The import specifier that *from_module* should use for *to_module*."""
        source = self.paths.get(from_module)
        target = self.paths.get(to_module)
        if source is None or target is None:
            return None
        source_dir = PurePosixPath(source).parent
        target_pure = PurePosixPath(target)
        relative = _relative_posix(source_dir, target_pure.parent)
        stem = target_pure.stem
        joined = f"{relative}/{stem}" if relative else f"./{stem}"
        return joined.replace("//", "/")


def _relative_posix(source_dir: PurePosixPath, target_dir: PurePosixPath) -> str:
    source_parts = [part for part in source_dir.parts if part not in ("", ".")]
    target_parts = [part for part in target_dir.parts if part not in ("", ".")]
    common = 0
    for left, right in zip(source_parts, target_parts, strict=False):
        if left != right:
            break
        common += 1
    upwards = [".."] * (len(source_parts) - common)
    downwards = target_parts[common:]
    if not upwards and not downwards:
        return "."
    return "/".join([*(upwards or ["."]), *downwards])


@dataclass
class GeneratedFile:
    """One generated target file and everything learned while generating it."""

    path: str
    source_path: str
    contents: str
    mappings: list[dict[str, Any]] = field(default_factory=list)
    diagnostics: DiagnosticBag = field(default_factory=DiagnosticBag)
    unsupported_count: int = 0

    @property
    def line_count(self) -> int:
        return self.contents.count("\n")

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "sourcePath": self.source_path,
            "lineCount": self.line_count,
            "unsupportedCount": self.unsupported_count,
            "diagnostics": self.diagnostics.to_list(),
        }


def generate_module(
    module: IRModule,
    layout: ModuleLayout | None = None,
    *,
    diagnostics: DiagnosticBag | None = None,
    dialect: Dialect | None = None,
) -> GeneratedFile:
    """Generate the ECMAScript file for *module* in the requested dialect."""
    dialect = dialect or TYPESCRIPT
    layout = layout or ModuleLayout.for_modules([module], dialect=dialect)
    output_path = layout.paths.get(module.name) or output_path_for(
        module.path, extension=dialect.extension
    )
    ctx = EmitContext(
        source_path=module.path,
        output_path=output_path,
        diagnostics=diagnostics if diagnostics is not None else DiagnosticBag(),
        emit_types=dialect.emit_types,
    )
    writer = CodeWriter()
    ctx.namespace_imports = _namespace_bindings(module)

    for line in _HEADER:
        writer.line(line.format(source=module.path or module.name))
    if module.docstring:
        writer.blank()
        _emit_doc_comment(module.docstring, writer)
    if module.imports:
        writer.blank()
        for imported in module.imports:
            _emit_import(imported, module, layout, writer, ctx)
    for statement in module.body:
        writer.blank()
        _emit_module_statement(statement, writer, ctx)
    for klass in module.classes:
        writer.blank()
        _emit_class(klass, writer, ctx)
    for function in module.functions:
        writer.blank()
        _emit_function(function, writer, ctx, exported=True)

    return GeneratedFile(
        path=output_path,
        source_path=module.path,
        contents=writer.render(),
        mappings=writer.mapping_dict(),
        diagnostics=ctx.diagnostics,
        unsupported_count=len(ctx.gaps),
    )


def _namespace_bindings(module: IRModule) -> dict[str, str]:
    """Dotted module path -> local binding, for this module's namespace imports.

    Both the absolute path and the path as written are recorded, because a
    relative ``import`` is referenced by the name the source used.
    """
    from codeweaver.graph.dependency import resolve_relative_import

    bindings: dict[str, str] = {}
    for imported in module.imports:
        if not imported.imports_whole_module:
            continue
        binding = imported.local_binding
        if imported.module:
            bindings[imported.module] = binding
        absolute = resolve_relative_import(module.name, imported.module, imported.level)
        if absolute:
            bindings[absolute] = binding
    return bindings


def _return_annotation(ir_type, ctx: EmitContext, *, is_async: bool = False) -> str:
    """``": T"`` for a typed dialect, ``""`` for an untyped one.

    JavaScript has no type syntax, so the same IR has to render without it.
    Keeping the decision here means a new annotation site cannot forget to ask.
    """
    if not ctx.emit_types:
        return ""
    rendered = render_return_type(ir_type)
    if is_async and not rendered.startswith("Promise<"):
        rendered = f"Promise<{rendered}>"
    return f": {rendered}"


def _visibility_modifiers(visibility: str, ctx: EmitContext) -> list[str]:
    """Visibility keywords this dialect accepts.

    ``private`` and ``protected`` are TypeScript-only.  JavaScript's ``#name``
    private fields are not an equivalent: they rename the member and are
    inaccessible to subclasses, so a faithful translation leaves the member
    public and lets the report carry the difference.
    """
    if not ctx.emit_types or visibility == Visibility.PUBLIC:
        return []
    return ["private" if visibility == Visibility.PRIVATE else "protected"]


def _emit_doc_comment(text: str, writer: CodeWriter) -> None:
    writer.line("/**")
    for line in text.strip().split("\n"):
        writer.line(f" * {line}".rstrip())
    writer.line(" */")


def _emit_import(
    imported: IRImport,
    module: IRModule,
    layout: ModuleLayout,
    writer: CodeWriter,
    ctx: EmitContext,
) -> None:
    from codeweaver.graph.dependency import resolve_relative_import

    absolute = resolve_relative_import(module.name, imported.module, imported.level)
    specifier = layout.specifier(module.name, absolute)
    if specifier is None:
        ctx.warn(
            "CW0640",
            f"import of {absolute or imported.module!r} is not a project module",
            span=imported.span,
            hint="install or re-implement the dependency in the target ecosystem",
        )
        specifier = absolute or imported.module
    quoted = f'"{specifier}"'
    if imported.imports_whole_module:
        # The binding comes from the IR so that the import statement and every
        # reference that reaches through it agree on one name.
        alias = safe_identifier(imported.local_binding)
        writer.line(f"import * as {alias} from {quoted};", imported.span)
        return
    names = ", ".join(
        safe_identifier(name.name)
        if not name.alias
        else f"{safe_identifier(name.name)} as {safe_identifier(name.alias)}"
        for name in imported.names
    )
    writer.line(f"import {{ {names} }} from {quoted};", imported.span)


def _emit_module_statement(statement, writer: CodeWriter, ctx: EmitContext) -> None:
    if isinstance(statement, IRVarDecl):
        keyword = "const" if statement.is_const else "let"
        name = safe_identifier(statement.name)
        annotation = (
            f": {render_type(statement.var_type)}"
            if ctx.emit_types and statement.var_type.kind is not TypeKind.UNKNOWN
            else ""
        )
        prefix = "export " if statement.name and not statement.name.startswith("_") else ""
        if statement.value is None:
            writer.line(f"{prefix}let {name}{annotation};", statement.span)
            return
        value = emit_expression(statement.value, ctx).text
        writer.line(f"{prefix}{keyword} {name}{annotation} = {value};", statement.span)
        return
    emit_statement(statement, writer, ctx)


def _emit_function(
    function: IRFunction, writer: CodeWriter, ctx: EmitContext, *, exported: bool
) -> None:
    if function.docstring:
        _emit_doc_comment(function.docstring, writer)
    for decorator in function.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    prefix = "export " if exported and function.visibility == Visibility.PUBLIC else ""
    asynchronous = "async " if function.is_async else ""
    params = emit_params(function.params, ctx)
    returns = _return_annotation(function.return_type, ctx, is_async=function.is_async)
    name = safe_identifier(function.name)
    writer.line(f"{prefix}{asynchronous}function {name}({params}){returns} {{", function.span)
    writer.indent()
    emit_block(function.body, writer, ctx)
    writer.dedent()
    writer.line("}")


def _emit_class(klass: IRClass, writer: CodeWriter, ctx: EmitContext) -> None:
    if klass.docstring:
        _emit_doc_comment(klass.docstring, writer)
    for decorator in klass.decorators:
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    if len(klass.bases) > 1:
        ctx.warn(
            "CW0641",
            f"class {klass.name!r} has {len(klass.bases)} base classes; "
            "TypeScript supports single inheritance",
            span=klass.span,
            hint="only the first base is extended; fold the others in manually",
        )
    extends = ""
    if klass.bases:
        extends = f" extends {_base_class_name(klass.bases[0], ctx)}"
    prefix = "export " if klass.visibility == Visibility.PUBLIC else ""
    writer.line(f"{prefix}class {safe_identifier(klass.name)}{extends} {{", klass.span)
    writer.indent()
    for item in klass.fields:
        _emit_field(item, writer, ctx)
    for method in klass.methods:
        if klass.fields or method is not klass.methods[0]:
            writer.blank()
        _emit_method(method, writer, ctx)
    writer.dedent()
    writer.line("}")


def _decorator_is_applied(decorator, method: IRFunction) -> bool:
    """Whether the backend turned *decorator* into a TypeScript modifier.

    Repeating an applied decorator as a "not applied" comment would be wrong,
    and for an accessor it would be actively misleading: ``@x.setter`` becomes
    ``set x(...)``, so it was applied.
    """
    text = decorator.source_text.lstrip("@")
    if text in _HANDLED_DECORATORS:
        return True
    return method.is_accessor and text.endswith((".setter", ".getter"))


def _setter_parameter(method: IRFunction, ctx: EmitContext) -> str:
    """The single parameter of a generated setter.

    Python allows a setter to take any name; TypeScript allows exactly one
    parameter and no return type.  A setter with the wrong arity is reported
    rather than emitted as something that would not compile.
    """
    if len(method.params) != 1:
        ctx.warn(
            "CW0643",
            f"property setter {method.name!r} takes {len(method.params)} parameter(s); "
            "a setter must take exactly one",
            span=method.span,
            hint="the first parameter is used and the rest are dropped",
        )
    if not method.params:
        return "value: unknown"
    return emit_params(method.params[:1], ctx)


def _base_class_name(base, ctx: EmitContext) -> str:
    """Render a base class, mapping a builtin Python exception onto Error.

    ``class MyError(Exception)`` has to extend something that exists at
    runtime; ``Exception`` does not, so without the mapping every custom
    exception class would fail to compile.
    """
    if isinstance(base, IRName) and is_builtin_exception(base.name):
        mapped = map_exception_name(base.name)
        ctx.warn(
            "CW0642",
            f"base class {base.name} is a Python builtin exception and becomes {mapped}",
            span=base.span,
            hint="the subclass keeps its own identity, but the hierarchy above it differs",
        )
        return safe_identifier(mapped)
    return emit_expression(base, ctx).text


def _emit_field(item, writer: CodeWriter, ctx: EmitContext) -> None:
    modifiers = _visibility_modifiers(item.visibility, ctx)
    if item.is_static:
        modifiers.append("static")
    prefix = f"{' '.join(modifiers)} " if modifiers else ""
    annotation = f": {render_type(item.field_type)}" if ctx.emit_types else ""
    # A field with no guaranteed initial value is optional, which is what makes
    # the class compile under strictPropertyInitialization.
    # The optional marker is what makes the class compile under
    # strictPropertyInitialization.  JavaScript has no such marker, so an
    # untyped dialect simply declares the field.
    optional = item.optional and item.default is None and ctx.emit_types
    name = f"{safe_property(item.name)}?" if optional else safe_property(item.name)
    if item.default is None:
        writer.line(f"{prefix}{name}{annotation};", item.span)
        return
    value = emit_expression(item.default, ctx).text
    writer.line(f"{prefix}{name}{annotation} = {value};", item.span)


def _emit_method(method: IRFunction, writer: CodeWriter, ctx: EmitContext) -> None:
    if method.docstring:
        _emit_doc_comment(method.docstring, writer)
    for decorator in method.decorators:
        if _decorator_is_applied(decorator, method):
            continue
        writer.line(f"// decorator not applied: {decorator.source_text or '<expression>'}")
    modifiers: list[str] = _visibility_modifiers(method.visibility, ctx)
    if method.is_static:
        modifiers.append("static")
    if method.is_abstract:
        if ctx.emit_types:
            modifiers.append("abstract")
        else:
            ctx.warn(
                "CW0644",
                f"abstract member {method.name!r} has no equivalent in this dialect",
                span=method.span,
                hint="the member is emitted without its abstract marker",
            )
    if method.is_async:
        modifiers.append("async")
    params = emit_params(method.params, ctx)
    if method.is_constructor:
        header = f"constructor({params})"
    elif method.accessor == ACCESSOR_GETTER:
        modifiers.append("get")
        returns = _return_annotation(method.return_type, ctx)
        header = f"{safe_property(method.name)}(){returns}"
    elif method.accessor == ACCESSOR_SETTER:
        # A TypeScript setter takes exactly one parameter and must not declare
        # a return type, so neither is emitted from the IR verbatim.
        modifiers.append("set")
        parameter = _setter_parameter(method, ctx)
        header = f"{safe_property(method.name)}({parameter})"
    else:
        returns = _return_annotation(method.return_type, ctx, is_async=method.is_async)
        header = f"{safe_property(method.name)}({params}){returns}"
    prefix = f"{' '.join(modifiers)} " if modifiers else ""
    if method.is_abstract:
        writer.line(f"{prefix}{header};", method.span)
        return
    writer.line(f"{prefix}{header} {{", method.span)
    writer.indent()
    previous_receiver = ctx.receiver
    ctx.receiver = str(method.meta.get("pythonReceiver", ""))
    emit_block(method.body, writer, ctx)
    ctx.receiver = previous_receiver
    writer.dedent()
    writer.line("}")
