"""The C11 target backend and the project files it scaffolds.

The generated project is a CMake project laid out like the C++ one:

* ``src/`` holds one header and one source file per Python module, plus the
  header-only runtime ``src/cw_runtime/cw.h``;
* every module with an ``if __name__ == "__main__":`` block gets its own
  ``<module>.main.c`` and an executable target;
* the build defaults to ``Release`` (``-O3``); int arithmetic is overflow
  checked, and ``-DCODEWEAVER_UNCHECKED=ON`` drops the checks for speed.

C is the narrowest target: values are ints, floats, bools, strings, lists and
project objects.  dict, set and tuple values, exception handling and
closures are reported as gaps rather than approximated.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from typing import Any

from codeweaver.backends.c.context import RUNTIME_HEADER, SOURCE_ROOT, CLayout
from codeweaver.backends.c.module import generate_module_files
from codeweaver.backends.common.files import GeneratedFile
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.project_index import ProjectIndex
from codeweaver.ir.declarations import IRModule

__all__ = ["CBackend", "render_cmakelists", "runtime_header"]


def runtime_header() -> str:
    """The C runtime shipped with the generated project."""
    return (
        resources.files("codeweaver.backends.c")
        .joinpath("runtime/cw.h")
        .read_text(encoding="utf-8")
    )


def _target_name(project_name: str) -> str:
    cleaned = (
        "".join(char if char.isalnum() else "_" for char in project_name) or "codeweaver_output"
    )
    return cleaned if not cleaned[0].isdigit() else f"p_{cleaned}"


def render_cmakelists(project_name: str, layout: CLayout) -> str:
    target = _target_name(project_name)
    sources = sorted(f"{SOURCE_ROOT}/{layout.source(module)}" for module in layout.stems)
    lines = [
        "# Generated by CodeWeaver. Review before use.",
        "cmake_minimum_required(VERSION 3.20)",
        f"project({target} LANGUAGES C)",
        "",
        "set(CMAKE_C_STANDARD 11)",
        "set(CMAKE_C_STANDARD_REQUIRED ON)",
        "set(CMAKE_C_EXTENSIONS OFF)",
        "if(NOT CMAKE_BUILD_TYPE)",
        "  set(CMAKE_BUILD_TYPE Release)",
        "endif()",
        "# Python never fuses a multiply and an add; FMA contraction would change",
        "# floating-point results in the last bits.",
        'if(CMAKE_C_COMPILER_ID MATCHES "GNU|Clang")',
        "  add_compile_options(-ffp-contract=off)",
        "endif()",
        "",
        'option(CODEWEAVER_UNCHECKED "Skip int overflow checks (faster; wraps instead of OverflowError)" OFF)',
        "",
        f"add_library({target}_lib STATIC",
        *(f"  {source}" for source in sources),
        ")",
        f"target_include_directories({target}_lib PUBLIC {SOURCE_ROOT})",
        "if(CODEWEAVER_UNCHECKED)",
        f"  target_compile_definitions({target}_lib PUBLIC CW_UNCHECKED)",
        "endif()",
        "find_library(MATH_LIBRARY m)",
        "if(MATH_LIBRARY)",
        f"  target_link_libraries({target}_lib PUBLIC ${{MATH_LIBRARY}})",
        "endif()",
    ]
    for module in sorted(layout.entry_modules):
        executable = _target_name(module.replace(".", "_"))
        lines += [
            "",
            f"add_executable({executable} {SOURCE_ROOT}/{layout.main_source(module)})",
            f"target_link_libraries({executable} PRIVATE {target}_lib)",
        ]
    return "\n".join(lines) + "\n"


@dataclass
class CBackend:
    """Backend adapter registered in the language registry."""

    language: str = "c"
    display_name: str = "C11"
    file_extension: str = ".c"
    supported_constructs: tuple[str, ...] = field(
        default_factory=lambda: (
            "modules as a header and a source file each, with collision-free global names",
            "classes as structs, single inheritance by embedding the base struct",
            "dynamic dispatch through function pointers, only for overridden methods",
            "constructors (Class_new) including super().__init__",
            "module-level statements run in import order at start-up",
            "for/else and while/else with exact semantics",
            "keyword arguments matched to the callee's signature, defaults filled in",
            "Python semantics for /, //, %, ** and negative, bounds-checked indexing",
            "growable lists of int, float, bool, str and objects; list comprehensions",
            "f-strings, str() and print() with Python's formatting (including float repr)",
            "raise as a Python-style error message and exit status 1",
            "builtins: len, print, str, repr, int, float, bool, abs, round, min, max, sum, sorted, list, range, ord",
            "common str and list methods",
            "math module functions and constants",
        )
    )
    known_limitations: tuple[str, ...] = field(
        default_factory=lambda: (
            "dict, set and tuple values are not translated",
            "try/except is not translated: C has no exceptions",
            "every parameter and variable needs a type the inference pass can determine",
            "memory is never freed (define CW_ALLOC to use a garbage collector)",
            "int is a 64-bit integer; Python's arbitrary precision is not modelled",
            "async/await, generators, with, match, lambdas and nested functions are reported",
        )
    )
    required_toolchains: tuple[str, ...] = field(default_factory=lambda: ("cc",))
    uses_type_inference: bool = True

    def create_layout(self, modules: list[IRModule], index: Any = None) -> CLayout:
        project = index if isinstance(index, ProjectIndex) else ProjectIndex.build(modules)
        return CLayout.build(modules, project)

    def generate_files(
        self, module: IRModule, layout: CLayout, *, diagnostics: DiagnosticBag | None = None
    ) -> list[GeneratedFile]:
        return generate_module_files(module, layout, diagnostics=diagnostics)

    def generate_module(
        self,
        module: IRModule,
        layout: CLayout | None = None,
        *,
        diagnostics: DiagnosticBag | None = None,
    ) -> GeneratedFile:
        """The module's header (the registry protocol's single-file view)."""
        layout = layout or self.create_layout([module])
        return self.generate_files(module, layout, diagnostics=diagnostics)[0]

    def project_files(self, project_name: str, layout: CLayout) -> dict[str, str]:
        return {
            "CMakeLists.txt": render_cmakelists(project_name, layout),
            f"{SOURCE_ROOT}/{RUNTIME_HEADER}": runtime_header(),
        }
