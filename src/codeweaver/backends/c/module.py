"""IR modules to C11 translation units.

Every Python module becomes a header (``algo.h``) and a source file
(``algo.c``); a module with an ``if __name__ == "__main__"`` block also gets
``algo.main.c`` holding ``main``.

Classes are structs.  A subclass embeds its base as its first member
(``Circle.base``), so a ``Circle*`` converts to a ``Shape*`` exactly as C
allows.  A method overridden anywhere in the hierarchy is stored as a
function pointer in the root struct and set by each ``Class_new``; every
other method is an ordinary function, which the compiler is free to inline.

Module-level statements run, in source order, in ``module_init()``, which
first initialises the modules it imports, so start-up order matches Python's
import order.
"""

from __future__ import annotations

from collections.abc import Callable

from codeweaver.backends.c.context import RUNTIME_HEADER, SOURCE_ROOT, CContext, CLayout
from codeweaver.backends.c.expressions import (
    dispatch_root,
    emit_expression,
    field_home,
    is_dispatched,
    member_path,
)
from codeweaver.backends.c.naming import safe_identifier
from codeweaver.backends.c.statements import emit_statement, flush
from codeweaver.backends.c.types import render_type, zero_value
from codeweaver.backends.common.analysis import (
    can_complete,
    escaping_loop_variables,
    is_main_guard,
    local_names,
)
from codeweaver.backends.common.files import GeneratedFile
from codeweaver.backends.common.strings import c_string_literal
from codeweaver.backends.common.writer import CodeWriter
from codeweaver.diagnostics import DiagnosticBag
from codeweaver.graph.dependency import resolve_relative_import
from codeweaver.graph.project_index import ClassInfo
from codeweaver.ir.base import walk
from codeweaver.ir.declarations import IRClass, IRFunction, IRModule
from codeweaver.ir.expressions import IRName
from codeweaver.ir.statements import IRBlock, IRVarDecl

__all__ = ["generate_module_files", "init_function"]

_HEADER = ("/* Generated by CodeWeaver from {source}. Review before use. */",)


def init_function(layout: CLayout, module: str) -> str:
    return f"{layout.stems[module].replace('/', '_')}_module_init"


def generate_module_files(
    module: IRModule, layout: CLayout, *, diagnostics: DiagnosticBag | None = None
) -> list[GeneratedFile]:
    ctx = CContext(
        source_path=module.path,
        output_path=layout.header(module.name),
        diagnostics=diagnostics if diagnostics is not None else DiagnosticBag(),
        layout=layout,
        index=layout.index,
        module=module,
    )
    header = _emit_header(module, layout, ctx)
    source = _emit_source(module, layout, ctx)
    files = [
        GeneratedFile(
            path=f"{SOURCE_ROOT}/{layout.header(module.name)}",
            source_path=module.path,
            contents=header.render(),
            mappings=header.mapping_dict(),
            diagnostics=ctx.diagnostics,
        ),
        GeneratedFile(
            path=f"{SOURCE_ROOT}/{layout.source(module.name)}",
            source_path=module.path,
            contents=source.render(),
            mappings=source.mapping_dict(),
            diagnostics=ctx.diagnostics,
        ),
    ]
    if module.name in layout.entry_modules:
        main = _emit_main(module, layout, ctx)
        files.append(
            GeneratedFile(
                path=f"{SOURCE_ROOT}/{layout.main_source(module.name)}",
                source_path=module.path,
                contents=main.render(),
                mappings=main.mapping_dict(),
                diagnostics=ctx.diagnostics,
            )
        )
    # Every gap found while writing any of the files is counted once, on the header.
    files[0].unsupported_count = len(ctx.gaps)
    files[0].gaps = list(ctx.gaps)
    return files


def _banner(writer: CodeWriter, module: IRModule) -> None:
    for line in _HEADER:
        writer.line(line.format(source=module.path or module.name))


def _doc(writer: CodeWriter, text: str) -> None:
    if not text:
        return
    writer.line("/*")
    for line in text.strip().split("\n"):
        writer.line(f" * {line.strip()}".rstrip().replace("*/", "* /"))
    writer.line(" */")


def _imports(module: IRModule, ctx: CContext) -> list[str]:
    found: list[str] = []
    for imported in module.imports:
        absolute = resolve_relative_import(module.name, imported.module, imported.level)
        candidates = [absolute]
        if not imported.imports_whole_module:
            candidates += [f"{absolute}.{name.name}" for name in imported.names]
        for candidate in candidates:
            if (
                ctx.index is not None
                and candidate in ctx.index.modules
                and candidate not in found
                and candidate != module.name
            ):
                found.append(candidate)
    return found


# -------------------------------------------------------------- signatures


def _first_report(ctx: CContext, function: IRFunction, part: str) -> bool:
    """A signature is written up to three times (header, source, thunk); report its gaps once."""
    key = (id(function), part)
    if key in ctx.signature_reports:
        return False
    ctx.signature_reports.add(key)
    return True


def _own(klass: IRClass, ctx: CContext) -> ClassInfo | None:
    return (
        ctx.index.classes.get(f"{ctx.module.name}.{klass.name}") if ctx.index is not None else None
    )


def _return_type(function: IRFunction, ctx: CContext) -> str:
    if function.is_constructor:
        return "void"
    spelled = render_type(function.return_type, ctx, returning=True)
    if spelled is None and _first_report(ctx, function, "return"):
        ctx.gap(
            "FunctionDef",
            f"return type of {function.name!r} has no C representation in this build",
            function.span,
            "annotate the return type; dict, set and tuple values are not translated to C",
        )
    return spelled or "void"


def _params(function: IRFunction, ctx: CContext, receiver: str = "") -> str:
    parts = [f"{receiver}* self"] if receiver else []
    for param in function.params:
        if param.style in ("var_positional", "var_keyword"):
            if _first_report(ctx, function, param.name):
                ctx.gap(
                    "FunctionDef",
                    f"*{param.name} / **{param.name} parameters are not translated to C",
                    function.span,
                )
            continue
        spelled = render_type(param.param_type, ctx)
        if spelled is None:
            if _first_report(ctx, function, param.name):
                ctx.gap(
                    "FunctionDef",
                    f"parameter {param.name!r} of {function.name!r} has no C type",
                    function.span,
                    "annotate the parameter",
                )
            spelled = "void*"
        parts.append(f"{spelled} {safe_identifier(param.name)}")
    return ", ".join(parts) or "void"


def _is_instance_method(method: IRFunction) -> bool:
    return not method.is_static and not method.meta.get("pythonClassMethod")


def _method_symbol(info: ClassInfo, method: IRFunction, ctx: CContext) -> str:
    name = "init" if method.is_constructor else safe_identifier(method.name)
    return f"{ctx.class_symbol(info)}_{name}"


def _method_prototype(info: ClassInfo, method: IRFunction, ctx: CContext) -> str:
    receiver = ctx.class_symbol(info) if _is_instance_method(method) else ""
    return f"{_return_type(method, ctx)} {_method_symbol(info, method, ctx)}({_params(method, ctx, receiver)})"


def _thunk_prototype(info: ClassInfo, method: IRFunction, ctx: CContext) -> str:
    root = dispatch_root(info, method.name, ctx)
    assert root is not None
    return (
        f"{_return_type(method, ctx)} {_method_symbol(info, method, ctx)}_vf"
        f"({_params(method, ctx, ctx.class_symbol(root))})"
    )


def _constructor_params(
    info: ClassInfo, ctx: CContext
) -> tuple[ClassInfo | None, IRFunction | None]:
    found = ctx.index.constructor(info) if ctx.index is not None else None
    return (found[0], found[1]) if found is not None else (None, None)


# -------------------------------------------------------------------- header


def _base_first(classes: list[IRClass], ctx: CContext) -> list[IRClass]:
    ordered: list[IRClass] = []
    by_name = {klass.name: klass for klass in classes}

    def visit(klass: IRClass) -> None:
        if klass in ordered:
            return
        info = _own(klass, ctx)
        prefix = f"{ctx.module.name}."
        if info is not None and info.base.startswith(prefix):
            base = by_name.get(info.base[len(prefix) :])
            if base is not None and base is not klass:
                visit(base)
        ordered.append(klass)

    for klass in classes:
        visit(klass)
    return ordered


def _emit_header(module: IRModule, layout: CLayout, ctx: CContext) -> CodeWriter:
    writer = CodeWriter()
    _banner(writer, module)
    guard = layout.guard(module.name)
    writer.line(f"#ifndef {guard}")
    writer.line(f"#define {guard}")
    writer.blank()
    writer.line(f'#include "{RUNTIME_HEADER}"')
    classes = [
        klass
        for klass in module.classes
        if (info := _own(klass, ctx)) is not None and not info.is_exception
    ]
    if classes:
        writer.blank()
        for klass in classes:
            info = _own(klass, ctx)
            assert info is not None
            symbol = ctx.class_symbol(info)
            writer.line(f"typedef struct {symbol} {symbol};")
    imports = _imports(module, ctx)
    if imports:
        writer.blank()
        for other in imports:
            writer.line(f'#include "{layout.header(other)}"')
    for klass in _base_first(classes, ctx):
        writer.blank()
        _emit_struct(klass, writer, ctx)
    writer.blank()
    writer.line(f"void {init_function(layout, module.name)}(void);")
    for statement in module.body:
        if isinstance(statement, IRVarDecl):
            spelled = render_type(statement.var_type, ctx)
            if spelled is None:
                marker = ctx.gap(
                    "Assign",
                    f"module variable {statement.name!r} has a type with no C representation",
                    statement.span,
                    "annotate the variable",
                )
                writer.line(
                    f"extern void* {ctx.symbol(module.name, statement.name)}; {marker}",
                    statement.span,
                )
                continue
            writer.line(
                f"extern {spelled} {ctx.symbol(module.name, statement.name)};", statement.span
            )
    for function in module.functions:
        _doc(writer, function.docstring)
        writer.line(
            f"{_return_type(function, ctx)} {ctx.symbol(module.name, function.name)}({_params(function, ctx)});",
            function.span,
        )
    writer.blank()
    writer.line(f"#endif /* {guard} */")
    return writer


def _emit_struct(klass: IRClass, writer: CodeWriter, ctx: CContext) -> None:
    info = _own(klass, ctx)
    assert info is not None and ctx.index is not None
    ctx.klass = info
    symbol = ctx.class_symbol(info)
    _doc(writer, klass.docstring)
    if len(klass.bases) > 1:
        ctx.warn(
            "CW0696",
            f"class {klass.name!r} has {len(klass.bases)} base classes; only the first project base is used",
            span=klass.span,
        )
    writer.line(f"struct {symbol} {{", klass.span)
    writer.indent()
    members_at = writer.line_count
    base = ctx.index.classes.get(info.base) if info.base else None
    if base is not None:
        writer.line(f"{ctx.class_symbol(base)} base;")
    for method in klass.methods:
        if method.is_constructor or not _is_instance_method(method):
            continue
        root = dispatch_root(info, method.name, ctx)
        if (
            root is not None
            and root.qualified == info.qualified
            and is_dispatched(info, method.name, ctx)
        ):
            writer.line(
                f"{_return_type(method, ctx)} (*vf_{safe_identifier(method.name)})({_params(method, ctx, symbol)});"
            )
    for item in klass.fields:
        home = field_home(info, item.name, ctx)
        if item.is_static or (home is not None and home.qualified != info.qualified):
            continue
        spelled = render_type(item.field_type, ctx)
        if spelled is None:
            marker = ctx.gap(
                "AnnAssign",
                f"field {item.name!r} has a type with no C representation",
                item.span,
                "annotate the field",
            )
            writer.line(f"void* {safe_identifier(item.name)}; {marker}", item.span)
            continue
        writer.line(f"{spelled} {safe_identifier(item.name)};", item.span)
    if writer.line_count == members_at:
        writer.line("char cw_empty; /* C structs cannot be empty */")
    writer.dedent()
    writer.line("};")
    for item in klass.fields:
        if item.is_static:
            spelled = render_type(item.field_type, ctx)
            if spelled is not None:
                writer.line(f"extern {spelled} {symbol}_{safe_identifier(item.name)};", item.span)
    _, constructor = _constructor_params(info, ctx)
    new_params = _params(constructor, ctx) if constructor is not None else "void"
    if not info.is_abstract:
        writer.line(f"{symbol}* {symbol}_new({new_params});")
    for method in klass.methods:
        writer.line(f"{_method_prototype(info, method, ctx)};", method.span)
        if (
            _is_instance_method(method)
            and not method.is_constructor
            and is_dispatched(info, method.name, ctx)
        ):
            writer.line(f"{_thunk_prototype(info, method, ctx)};")
    ctx.klass = None


# -------------------------------------------------------------------- source


def _is_docstring(statement) -> bool:
    expression = getattr(statement, "expression", None)
    return getattr(expression, "kind", "") == "literal" and isinstance(
        getattr(expression, "value", None), str
    )


def _emit_source(module: IRModule, layout: CLayout, ctx: CContext) -> CodeWriter:
    writer = CodeWriter()
    _banner(writer, module)
    writer.line(f'#include "{layout.header(module.name)}"')
    writer.blank()
    for statement in module.body:
        if isinstance(statement, IRVarDecl):
            spelled = render_type(statement.var_type, ctx) or "void*"
            writer.line(
                f"{spelled} {ctx.symbol(module.name, statement.name)} = {zero_value(spelled)};",
                statement.span,
            )
    for klass in module.classes:
        info = _own(klass, ctx)
        if info is None or info.is_exception:
            continue
        for item in klass.fields:
            static_type = render_type(item.field_type, ctx) if item.is_static else None
            if static_type is not None:
                writer.line(
                    f"{static_type} {ctx.class_symbol(info)}_{safe_identifier(item.name)} = {zero_value(static_type)};"
                )
    _emit_module_init(module, layout, writer, ctx)
    for klass in module.classes:
        info = _own(klass, ctx)
        if info is None:
            continue
        if info.is_exception:
            ctx.warn(
                "CW0697",
                f"exception class {klass.name!r} has no C counterpart; raising it prints its name and exits",
                span=klass.span,
            )
            continue
        ctx.klass = info
        if not info.is_abstract:
            writer.blank()
            _emit_new(info, writer, ctx)
        for method in klass.methods:
            writer.blank()
            _emit_method(info, method, writer, ctx)
        ctx.klass = None
    for function in module.functions:
        writer.blank()
        for decorator in function.decorators:
            writer.line(f"/* decorator not applied: {decorator.source_text or '<expression>'} */")
        writer.line(
            f"{_return_type(function, ctx)} {ctx.symbol(module.name, function.name)}({_params(function, ctx)}) {{",
            function.span,
        )
        writer.indent()
        _emit_body(function, function.body, writer, ctx)
        writer.dedent()
        writer.line("}")
    return writer


def _emit_module_init(module: IRModule, layout: CLayout, writer: CodeWriter, ctx: CContext) -> None:
    writer.blank()
    writer.line(f"void {init_function(layout, module.name)}(void) {{")
    writer.indent()
    writer.line("static bool done = false;")
    writer.line("if (done) return;")
    writer.line("done = true;")
    for other in _imports(module, ctx):
        writer.line(f"{init_function(layout, other)}();")
    for klass in module.classes:
        info = _own(klass, ctx)
        if info is None or info.is_exception:
            continue
        for item in klass.fields:
            if (
                item.is_static
                and item.default is not None
                and render_type(item.field_type, ctx) is not None
            ):
                value = emit_expression(item.default, ctx, item.field_type).text
                flush(writer, ctx)
                writer.line(
                    f"{ctx.class_symbol(info)}_{safe_identifier(item.name)} = {value};", item.span
                )

    def body(into: CodeWriter) -> None:
        for statement in module.body:
            if (
                is_main_guard(statement)
                or statement.kind in ("comment", "noop")
                or _is_docstring(statement)
            ):
                continue
            if isinstance(statement, IRVarDecl):
                if statement.value is None or render_type(statement.var_type, ctx) is None:
                    continue
                value = emit_expression(statement.value, ctx, statement.var_type).text
                flush(into, ctx)
                into.line(f"{ctx.symbol(module.name, statement.name)} = {value};", statement.span)
                continue
            emit_statement(statement, into, ctx)

    _guarded(writer, ctx, f"importing {module.name}", body)
    writer.dedent()
    writer.line("}")


def _emit_new(info: ClassInfo, writer: CodeWriter, ctx: CContext) -> None:
    assert ctx.index is not None
    symbol = ctx.class_symbol(info)
    owner, constructor = _constructor_params(info, ctx)
    params = _params(constructor, ctx) if constructor is not None else "void"
    writer.line(f"{symbol}* {symbol}_new({params}) {{")
    writer.indent()
    writer.line(f"{symbol}* self = ({symbol}*)cw_alloc(sizeof *self);")
    writer.line("memset(self, 0, sizeof *self);")
    names: list[str] = []
    for klass in reversed(ctx.index.ancestors(info)):
        for name, method in klass.methods.items():
            if name not in names and _is_instance_method(method) and not method.is_constructor:
                names.append(name)
    for name in names:
        if not is_dispatched(info, name, ctx):
            continue
        root = dispatch_root(info, name, ctx)
        found = ctx.index.find_method(info, name)
        if root is None or found is None:
            continue
        implementation, method = found
        path = member_path(info, root, ctx)
        writer.line(
            f"self->{path}vf_{safe_identifier(name)} = {_method_symbol(implementation, method, ctx)}_vf;"
        )
    for klass in reversed(ctx.index.ancestors(info)):
        for item in klass.node.fields:
            if item.is_static or item.default is None or render_type(item.field_type, ctx) is None:
                continue

            value = emit_expression(item.default, ctx, item.field_type).text
            flush(writer, ctx)
            writer.line(
                f"self->{member_path(info, klass, ctx)}{safe_identifier(item.name)} = {value};"
            )
    if owner is not None and constructor is not None:
        args = ", ".join(
            safe_identifier(param.name)
            for param in constructor.params
            if param.style not in ("var_positional", "var_keyword")
        )
        receiver = (
            "self" if owner.qualified == info.qualified else f"({ctx.class_symbol(owner)}*)self"
        )
        writer.line(
            f"{ctx.class_symbol(owner)}_init({', '.join(part for part in (receiver, args) if part)});"
        )
    writer.line("return self;")
    writer.dedent()
    writer.line("}")


def _emit_method(info: ClassInfo, method: IRFunction, writer: CodeWriter, ctx: CContext) -> None:
    for decorator in method.decorators:
        if decorator.source_text not in (
            "staticmethod",
            "property",
            "abstractmethod",
            "abc.abstractmethod",
        ):
            writer.line(f"/* decorator not applied: {decorator.source_text or '<expression>'} */")
    writer.line(f"{_method_prototype(info, method, ctx)} {{", method.span)
    writer.indent()
    _emit_body(method, method.body, writer, ctx)
    writer.dedent()
    writer.line("}")
    if (
        _is_instance_method(method)
        and not method.is_constructor
        and is_dispatched(info, method.name, ctx)
    ):
        args = ", ".join(
            [f"({ctx.class_symbol(info)}*)self"]
            + [
                safe_identifier(param.name)
                for param in method.params
                if param.style not in ("var_positional", "var_keyword")
            ]
        )
        call = f"{_method_symbol(info, method, ctx)}({args})"
        returns = _return_type(method, ctx) != "void"
        writer.line(
            f"{_thunk_prototype(info, method, ctx)} {{ {'return ' if returns else ''}{call}; }}"
        )


def _emit_body(function: IRFunction, block: IRBlock, writer: CodeWriter, ctx: CContext) -> None:
    ctx.function = function
    ctx.locals = local_names(function)
    receiver = str(function.meta.get("pythonReceiver", ""))
    ctx.receiver = "" if function.meta.get("pythonClassMethod") else receiver
    ctx.locals.discard(receiver)
    ctx.escaping = escaping_loop_variables(block)
    ctx.declared = {node.name for node in walk(block) if isinstance(node, IRVarDecl)} & ctx.escaping
    if block.is_empty:
        writer.line("/* pass */")
    names_used = {node.name for node in walk(block) if isinstance(node, IRName)}
    if ctx.receiver and ctx.receiver not in names_used:
        writer.line("(void)self;")
    for param in function.params:
        # An unused parameter is legal Python; silence C's warning for it.
        if param.name not in names_used:
            writer.line(f"(void){safe_identifier(param.name)};")
    signature_ok = _signature_ok(function, ctx)

    def body(into: CodeWriter) -> None:
        for statement in block.statements:
            emit_statement(statement, into, ctx)
        returns = function.name != "__main__" and not function.is_constructor
        if returns and _return_type(function, ctx) != "void" and can_complete(block):
            # Python would return None here; this C return type has no None.
            into.line('cw_raise("TypeError", "function ended without returning a value");')

    # A stub disables the body, so parameters only the body read become unused.
    stub_voids = [
        safe_identifier(param.name) for param in function.params if param.name in names_used
    ]
    if ctx.receiver and ctx.receiver in names_used:
        stub_voids.insert(0, "self")
    _guarded(writer, ctx, function.name, body, broken=not signature_ok, stub_voids=stub_voids)
    ctx.function = None
    ctx.locals = set()
    ctx.receiver = ""
    ctx.escaping = set()
    ctx.declared = set()


def _signature_ok(function: IRFunction, ctx: CContext) -> bool:
    if (
        not function.is_constructor
        and function.name != "__main__"
        and render_type(function.return_type, ctx, returning=True) is None
    ):
        return False
    return all(
        param.style not in ("var_positional", "var_keyword")
        and render_type(param.param_type, ctx) is not None
        for param in function.params
    )


def _guarded(
    writer: CodeWriter,
    ctx: CContext,
    what: str,
    emit: Callable[[CodeWriter], None],
    *,
    broken: bool = False,
    stub_voids: list[str] | None = None,
) -> None:
    """Write *emit*'s statements, or a stub if they contain a gap.

    A gap's placeholder has no C type that fits every context, so a body with a
    gap would not compile.  Such a body is replaced by a call that stops the
    program with NotImplementedError, and the partial translation is kept,
    disabled, below it for the reviewer.  The gaps themselves are already
    recorded, so the report is INCOMPLETE either way.
    """
    sub = CodeWriter(indent_text=writer.indent_text)
    for _ in range(writer.level):
        sub.indent()
    before = len(ctx.gaps)
    emit(sub)
    if len(ctx.gaps) == before and not broken:
        writer.extend(sub)
        return
    for gap in ctx.gaps[before:]:
        writer.line(ctx.marker(gap), gap.span)
    for name in stub_voids or []:
        writer.line(f"(void){name};")
    writer.line(
        f"cw_unsupported({c_string_literal(f'{what} uses constructs not translated to C', trigraphs=True)});"
    )
    writer.line("#if 0 /* partial translation, kept for review */")
    writer.extend(sub)
    writer.line("#endif")


# ---------------------------------------------------------------------- main


def _emit_main(module: IRModule, layout: CLayout, ctx: CContext) -> CodeWriter:
    writer = CodeWriter()
    _banner(writer, module)
    writer.line(f'#include "{layout.header(module.name)}"')
    writer.blank()
    writer.line("int main(void) {")
    writer.indent()
    writer.line(f"{init_function(layout, module.name)}();")
    guard = next(statement for statement in module.body if is_main_guard(statement))
    body = guard.then_body  # type: ignore[attr-defined]
    fake = IRFunction("__main__", body=body)
    _emit_body(fake, body, writer, ctx)
    writer.line("return 0;")
    writer.dedent()
    writer.line("}")
    return writer
